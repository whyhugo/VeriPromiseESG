"""One scoring convention, applied everywhere, with the API failures counted.

Two problems in the project's own numbers made this necessary.

First, a failed API call was being scored as a free guess. Scripts 26 and 45 both
read a cached response as `v[0] or "Clear"`, so a model that returned nothing --
an HTTP 503, a timeout -- was recorded as having answered `Clear`. On a set that
is 83% `Clear`, that is not a neutral default; it is a correct answer handed to
the model for failing to respond. One model has 80 such rows.

Second, two conventions for an out-of-set prediction coexist. Script 26 maps a
predicted `N/A` to `Clear`; script 45 maps it to an index outside the label set
so that it counts as wrong. The two give different numbers for the same model,
and the difference is not small.

This script fixes one convention and reports everything under it:

  * a response that failed or could not be parsed is **excluded**, and the
    exclusion is reported per model. It is not scored as anything.
  * a prediction of `N/A` on a row that has evidence is **wrong**. The row had
    evidence, so `N/A` is not an available correct answer.

It then re-derives the unanimity split under that convention, because a row
counted as unanimous only through a coerced failure is not unanimous, and
computes the error-correlation values the paper quotes, which until now existed
only in a scratch file.

CPU only.
"""
import csv
import io
import itertools
import json
import os
import sys

import numpy as np
from sklearn.metrics import f1_score

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "data", "veripromiseesgdataset")
OUT = os.path.join(ROOT, "research", "output")
S26 = os.path.join(ROOT, "research", "artifacts", "s26")
S36 = os.path.join(ROOT, "research", "artifacts", "s36")
S44 = os.path.join(ROOT, "research", "artifacts", "s44")
os.makedirs(OUT, exist_ok=True)
EQ = ["Clear", "Not Clear", "Misleading"]
SEED = 20260830


def load(fn):
    return list(csv.DictReader(open(os.path.join(D, fn), encoding="utf-8-sig")))


def na(v):
    v = (v or "").strip()
    return "N/A" if v in ("", "N/A") else v


def main():
    te = load("vpesg4k_test_2000.csv")
    rows = {r["id"]: r for r in te
            if na(r["evidence_status"]) == "Yes" and na(r["evidence_quality"]) in EQ}
    ids = sorted(rows)
    gold = {i: na(rows[i]["evidence_quality"]) for i in ids}

    # raw[model][id] = (label or "", error string or "")
    raw = {}
    for f in sorted(os.listdir(S26)):
        if not f.endswith(".json"):
            continue
        g = json.load(open(os.path.join(S26, f), encoding="utf-8"))
        raw[f.split("__")[0]] = {k: (v[0] or "", (v[2] if len(v) > 2 else "") or "")
                                 for k, v in g.items()}
    models = sorted(raw)

    L = []
    A = L.append
    A("# One scoring convention")
    A("")
    A("Generated by `research/scripts/47_scoring_convention.py`.")
    A("")
    A("## How often did a call actually fail?")
    A("")
    A("A cached response with empty text is a failed call, not an answer. Until "
      "now these were read as `v[0] or \"Clear\"` and scored as a correct guess "
      "on a set that is 82.8% `Clear`.")
    A("")
    A("| model | rows | empty response | predicted `N/A` | usable |")
    A("|---|---:|---:|---:|---:|")
    ok_ids = {}
    for m in models:
        have = [i for i in ids if i in raw[m]]
        empty = [i for i in have if not raw[m][i][0]]
        naa = [i for i in have if raw[m][i][0] == "N/A"]
        ok_ids[m] = [i for i in have if raw[m][i][0]]
        A("| %s | %d | **%d** | %d | %d |"
          % (m, len(have), len(empty), len(naa), len(ok_ids[m])))
    A("")

    A("## The same models under the two conventions")
    A("")
    A("`old` is what scripts 26 and 45 did: an empty response and an `N/A` both "
      "become `Clear`. `new` excludes the failures and counts a predicted `N/A` "
      "as wrong, since these rows all have evidence.")
    A("")
    A("| model | old macro-F1 | old acc. | new macro-F1 | new acc. | rows scored |")
    A("|---|---:|---:|---:|---:|---:|")
    for m in models:
        have = [i for i in ids if i in raw[m]]
        y_old = [gold[i] for i in have]
        p_old = [raw[m][i][0] if raw[m][i][0] in EQ else "Clear" for i in have]
        keep = ok_ids[m]
        y_new = [gold[i] for i in keep]
        p_new = [raw[m][i][0] if raw[m][i][0] in EQ else "__wrong__" for i in keep]
        A("| %s | %.4f | %.4f | %.4f | %.4f | %d |"
          % (m,
             f1_score(y_old, p_old, average="macro", labels=EQ, zero_division=0),
             np.mean([a == b for a, b in zip(y_old, p_old)]),
             f1_score(y_new, p_new, average="macro", labels=EQ, zero_division=0),
             np.mean([a == b for a, b in zip(y_new, p_new)]),
             len(keep)))

    z = np.load(os.path.join(S36, "cond_A.npz"))
    te_rows = [r for r in te if na(r["evidence_status"]) == "Yes"
               and na(r["evidence_quality"]) in EQ]
    enc = {r["id"]: EQ[k] for r, k in zip(te_rows, z["test"].argmax(1))}
    y = [gold[i] for i in ids]
    pe = [enc[i] for i in ids]
    A("| **本文微調編碼器** | %.4f | %.4f | %.4f | %.4f | %d |"
      % (f1_score(y, pe, average="macro", labels=EQ, zero_division=0),
         np.mean([a == b for a, b in zip(y, pe)]),
         f1_score(y, pe, average="macro", labels=EQ, zero_division=0),
         np.mean([a == b for a, b in zip(y, pe)]), len(ids)))
    A("")

    A("## The unanimity split, with failures excluded")
    A("")
    A("A row is only unanimous if all four models actually answered it.")
    A("")
    both = [i for i in ids if all(i in raw[m] and raw[m][i][0] for m in models)]
    unan = [i for i in both if len({raw[m][i][0] for m in models}) == 1]
    wrong = [i for i in unan if raw[models[0]][i][0] != gold[i]]
    right = [i for i in unan if raw[models[0]][i][0] == gold[i]]

    old_all = [i for i in ids if all(i in raw[m] for m in models)]
    old_lab = {m: {i: (raw[m][i][0] or "Clear") for i in old_all} for m in models}
    old_un = [i for i in old_all if len({old_lab[m][i] for m in models}) == 1]
    old_w = [i for i in old_un if old_lab[models[0]][i] != gold[i]]

    A("| | 以往（失敗計為 Clear） | 修正後（排除失敗） |")
    A("|---|---:|---:|")
    A("| 四模型一致 | %d | %d |" % (len(old_un), len(unan)))
    A("| 一致且正確（對照組） | %d | %d |" % (len(old_un) - len(old_w), len(right)))
    A("| 一致但錯誤（爭議組） | %d | %d |" % (len(old_w), len(wrong)))
    A("")
    A("%d 段先前被算成「四模型一致」，實際上只有三個模型作答；其中 %d 段落在對照組、"
      "%d 段落在爭議組。**方向與量級不變，但敘述必須改成「四個模型都作答且答案相同」**。"
      % (len(old_un) - len(unan),
         len(set(old_un) - set(unan) - set(old_w)),
         len(set(old_w) - set(wrong))))
    A("")

    A("## 錯誤相關係數")
    A("")
    A("兩個系統各自的「這一列答錯了沒」向量之間的相關係數（Matthews / phi）。"
      "只在兩者都有作答的列上計算。")
    A("")
    err = {}
    for m in models:
        err[m] = {i: int((raw[m][i][0] if raw[m][i][0] in EQ else "__wrong__")
                         != gold[i]) for i in ok_ids[m]}
    err["本文微調編碼器"] = {i: int(enc[i] != gold[i]) for i in ids}
    bp = os.path.join(S44, "base_Qwen_Qwen3-8B.json")
    if os.path.exists(bp):
        pq = np.array(json.load(open(bp, encoding="utf-8"))["test"]).argmax(1)
        qw = {r["id"]: EQ[k] for r, k in zip(te_rows, pq)}
        err["Qwen3-8B"] = {i: int(qw[i] != gold[i]) for i in ids}

    def phi(a, b):
        k = [i for i in err[a] if i in err[b]]
        x = np.array([err[a][i] for i in k])
        y2 = np.array([err[b][i] for i in k])
        if x.std() == 0 or y2.std() == 0:
            return float("nan"), len(k)
        return float(np.corrcoef(x, y2)[0, 1]), len(k)

    fr = models
    pairs = [phi(a, b)[0] for a, b in itertools.combinations(fr, 2)]
    A("| 組合 | $\\phi$ | 計算列數 |")
    A("|---|---:|---:|")
    A("| 四個前沿模型彼此（6 組配對平均） | **%.3f** | --- |" % np.mean(pairs))
    for a, b in [("本文微調編碼器", "Qwen3-8B")]:
        if b in err:
            v, n = phi(a, b)
            A("| %s 與 %s | **%.3f** | %d |" % (a, b, v, n))
    A("")
    A("先前 scratch 計算得到 0.498 與 0.307，是把失敗回應計為 `Clear` 之後的結果；"
      "上表為排除失敗後的值。")
    A("")

    A("## 這對論文的影響")
    A("")
    A("失敗回應被當成免費的 `Clear` 猜測，會\\textbf{高估}該模型的成績，而受影響最深的"
      "是失敗次數最多的那一個。分歧分析的兩組也因此混入了「其實只有三個模型作答」的列。"
      "更正後方向與量級都不變，但論文必須改用本節的數字，並把「四個模型答案完全相同」"
      "改寫為「四個模型都作答且答案相同」。")
    A("")

    dest = os.path.join(OUT, "scoring_convention.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", dest, flush=True)
    print("\n".join(L))


if __name__ == "__main__":
    main()
