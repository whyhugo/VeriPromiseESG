"""Does retrieval survive the same test that killed the LLM vote?

Stage A found the retrieval premise holds: a paragraph's nearest neighbours
carry its label 1.11x to 1.45x more often than chance, and a retrieval-only
classifier is right on 13-16% of rows the encoder gets wrong. Those are the same
numbers the LLM sweep produced before honest weight fitting reduced its gain to
nothing, so complementarity alone proves nothing.

This applies the identical protocol to the retrieval signal. The train+val rows
are split in half, stratified; the mixing weight between the encoder's
out-of-fold probability and the retrieval probability is fitted on one half and
the gain read off the other, then swapped and averaged. Every number is out of
sample with respect to the weight, and the oracle column stays only as the
ceiling it is.

Two signals are tested separately and together:
  knn      the similarity-weighted neighbour vote from stage A
  fewshot  the language model prompted with those neighbours, from stage B

Running both matters because they use the same retrieval in different ways. If
neither adds anything, the failure is retrieval itself rather than how it was
consumed.
"""
import csv
import io
import json
import os
import sys

import numpy as np
from sklearn.metrics import f1_score
from sklearn.model_selection import StratifiedKFold

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "data", "veripromiseesgdataset")
OUT = os.path.join(ROOT, "research", "output")
S18 = os.path.join(ROOT, "research", "artifacts", "s18")
S21 = os.path.join(ROOT, "research", "artifacts", "s21")
S23 = os.path.join(ROOT, "research", "artifacts", "s23")
SEED = 20260824

LABELS = {
    "promise_status": ["No", "Yes"],
    "evidence_status": ["N/A", "No", "Yes"],
    "evidence_quality": ["N/A", "Not Clear", "Clear", "Misleading"],
    "verification_timeline": ["N/A", "already", "within_2_years",
                              "between_2_and_5_years", "more_than_5_years"],
}
COMP_W = {"promise_status": 0.20, "evidence_status": 0.30,
          "evidence_quality": 0.35, "verification_timeline": 0.15}
WEIGHTS = np.arange(0.0, 0.81, 0.05)


def load(fn):
    return list(csv.DictReader(open(os.path.join(D, fn), encoding="utf-8-sig")))


def na(v):
    v = (v or "").strip()
    return "N/A" if v in ("", "N/A") else v


def macro(y, p):
    return f1_score(y, p, average="macro", zero_division=0)


def honest(y, base, extra):
    """Fit the weight on one stratified half, measure on the other, swap, mean."""
    skf = StratifiedKFold(n_splits=2, shuffle=True, random_state=SEED)
    gains, ws = [], []
    for tr, te in skf.split(np.zeros(len(y)), y):
        sc = [macro(y[tr], ((1 - w) * base[tr] + w * extra[tr]).argmax(1))
              for w in WEIGHTS]
        w = WEIGHTS[int(np.argmax(sc))]
        ws.append(w)
        gains.append(macro(y[te], ((1 - w) * base[te] + w * extra[te]).argmax(1))
                     - macro(y[te], base[te].argmax(1)))
    return float(np.mean(gains)), ws


def oracle(y, base, extra):
    sc = [macro(y, ((1 - w) * base + w * extra).argmax(1)) for w in WEIGHTS]
    i = int(np.argmax(sc))
    return sc[i] - macro(y, base.argmax(1)), WEIGHTS[i]


def main():
    trv = load("vpesg4k_train_1000") + load("vpesg4k_val_1000")
    knn = np.load(os.path.join(S23, "knn_probs.npz"))
    pick = json.load(open(os.path.join(S21, "subsample.json")))["picked_rows"]

    L = []
    A = L.append
    A("# Does retrieval survive honest weight fitting?")
    A("")
    A("Generated by `research/scripts/24_retrieval_gain.py`. Same protocol as "
      "script 22: the rows are split in half, stratified; the mixing weight is "
      "fitted on one half and the gain measured on the other, then swapped and "
      "averaged. The oracle column is a ceiling, not a result.")
    A("")

    A("## Neighbour vote mixed into the encoder (all 2,000 train+val rows)")
    A("")
    A("| subtask | encoder alone | oracle w | oracle gain | **honest gain** | fitted w (A / B) |")
    A("|---|---:|---:|---:|---:|---|")
    tot = 0.0
    for f in LABELS:
        y = np.array([LABELS[f].index(na(r[f])) for r in trv])
        eo = np.load(os.path.join(S18, "%s.npz" % f.replace("_", "")))["oof"]
        kp = knn[f]
        og, ow = oracle(y, eo, kp)
        hg, ws = honest(y, eo, kp)
        tot += COMP_W[f] * max(0.0, hg)
        A("| `%s` | %.4f | %.2f | %+.4f | **%+.4f** | %.2f / %.2f |"
          % (f, macro(y, eo.argmax(1)), ow, og, hg, ws[0], ws[1]))
    A("")
    A("Keeping only the non-negative gains, the weighted total moves "
      "**%+.4f**." % tot)
    A("")

    # ---- stage B, if it has run ----
    fs = {f: os.path.join(S23, "fewshot_%s.npz" % f.replace("_", ""))
          for f in LABELS}
    if all(os.path.exists(p) for p in fs.values()):
        A("## Retrieved examples in the prompt, mixed into the encoder")
        A("")
        A("On the %d-row subsample, so these are directly comparable to the "
          "zero-shot rows of script 22." % len(pick))
        A("")
        A("| subtask | encoder alone | oracle gain | **honest gain** | zero-shot honest (script 22) |")
        A("|---|---:|---:|---:|---:|")
        ZS = {"promise_status": "+0.0007", "evidence_status": "-0.0026",
              "evidence_quality": "-0.0197", "verification_timeline": "-0.0194"}
        tot2 = 0.0
        for f in LABELS:
            y = np.array([LABELS[f].index(na(trv[i][f])) for i in pick])
            eo = np.load(os.path.join(S18, "%s.npz" % f.replace("_", "")))["oof"][pick]
            fp = np.load(fs[f])["p"]
            og, _ = oracle(y, eo, fp)
            hg, _ = honest(y, eo, fp)
            tot2 += COMP_W[f] * max(0.0, hg)
            A("| `%s` | %.4f | %+.4f | **%+.4f** | %s |"
              % (f, macro(y, eo.argmax(1)), og, hg, ZS[f]))
        A("")
        A("Weighted total from the non-negative gains: **%+.4f**. The last "
          "column is the same model, same subsample, prompted with the "
          "guideline's wording instead of retrieved examples." % tot2)
        A("")

        A("## Three-way mix: encoder + neighbour vote + retrieved-example prompt")
        A("")
        A("| subtask | **honest gain** |")
        A("|---|---:|")
        tot3 = 0.0
        for f in LABELS:
            y = np.array([LABELS[f].index(na(trv[i][f])) for i in pick])
            eo = np.load(os.path.join(S18, "%s.npz" % f.replace("_", "")))["oof"][pick]
            mix = (knn[f][pick] + np.load(fs[f])["p"]) / 2.0
            hg, _ = honest(y, eo, mix)
            tot3 += COMP_W[f] * max(0.0, hg)
            A("| `%s` | **%+.4f** |" % (f, hg))
        A("")
        A("Weighted total: **%+.4f**." % tot3)
        A("")
    else:
        A("*Stage B outputs not present; run script 23 with `--stage AB` first.*")
        A("")

    dest = os.path.join(OUT, "retrieval_gain.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", dest, flush=True)
    print("\n".join(L))


if __name__ == "__main__":
    main()
