"""Inventory the released ML-Promise / PromiseEval dataset and check what is
actually usable as an external corpus for the VeriPromiseESG4K work.

Source: http://MLpromise.nlpfin.com/ -> public Google Drive folder
        (Training/ and Test/ JSON per language; ESG_Reports_Chinese/ has the
        10 Taiwanese source PDFs; EN_FR_Reports/ has zipped EN/FR reports).
Licence: CC BY-NC-SA 4.0 per Seki et al. (2025) Section 7.

The point of this script is to establish, per language:
  * how many instances were actually released (vs what the paper reports)
  * whether the paragraph text field (`data`) is present -- without it the
    corpus cannot be used for classification or extraction without first
    re-extracting text from the source PDFs
  * whether span annotations are present
  * the real supply of Misleading instances
and, for Chinese, which companies overlap with VeriPromiseESG4K.
"""
import io
import json
import os
import sys
from collections import Counter

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MLP = os.path.join(ROOT, "research", "data", "raw", "mlpromise")
OUT = os.path.join(ROOT, "research", "output")
os.makedirs(OUT, exist_ok=True)

LANGS = ["Chinese", "English", "French", "Japanese", "Korean"]

# ML-Promise Chinese source PDFs -> TWSE ticker, where the company also appears
# in VeriPromiseESG4K. Matched via the URL host / company name in the released
# URL field. Companies with no VeriPromiseESG4K counterpart map to None.
PDF_TO_TICKER = {
    "TSMC.pdf": "2330",
    "FPCC.pdf": "6505",
    "NPC.pdf": "1303",
    "Alchip.pdf": "3661",
    "SPT.pdf": None,          # ScinoPharm
    "KYE.pdf": None,          # KYE Systems / Genius
    "PSI.pdf": None,          # Phoenix Silicon International
    "Standard.pdf": None,
    "pegavision.pdf": None,
    "GTG.pdf": None,          # Great Taipei Gas
}


def load(path):
    j = json.load(open(path, encoding="utf-8-sig"))
    return j.get("data", list(j.values())[0]) if isinstance(j, dict) else j


def load_lang(lang):
    rows = []
    for split, fn in [("train", "Trainset_%s.json"), ("test", "Test_%s.json")]:
        p = os.path.join(MLP, fn % lang)
        if os.path.exists(p):
            for r in load(p):
                r["_split"] = split
            rows += load(p) if False else [r for r in load(p)]
    # reload with split tags (kept simple and explicit)
    rows = []
    for split, fn in [("train", "Trainset_%s.json"), ("test", "Test_%s.json")]:
        p = os.path.join(MLP, fn % lang)
        if not os.path.exists(p):
            continue
        for r in load(p):
            r["_split"] = split
            rows.append(r)
    return rows


def load_vpesg():
    rows = []
    for fn in ["vpesg_4k_train_1000.json", "vpesg4k_val_1000.json"]:
        d = load(os.path.join(ROOT, "data", fn))
        rows += d
    return rows


def main():
    lines = []
    A = lines.append
    A("# ML-Promise / PromiseEval released-data inventory")
    A("")
    A("Generated by `research/scripts/03_mlpromise_inventory.py`. "
      "Source: <http://MLpromise.nlpfin.com/> (public Drive folder), "
      "licence CC BY-NC-SA 4.0.")
    A("")

    A("## 1. What was actually released, per language")
    A("")
    A("| Language | train | test | total | `data` (paragraph text) | spans | ESG type | Misleading |")
    A("|---|---:|---:|---:|:--:|:--:|:--:|---:|")

    totals = {}
    mis_total = 0
    for lang in LANGS:
        rows = load_lang(lang)
        if not rows:
            continue
        ntr = sum(1 for r in rows if r["_split"] == "train")
        nte = sum(1 for r in rows if r["_split"] == "test")
        keys = set(rows[0].keys())
        has_data = "data" in keys
        has_span = "promise_string" in keys
        has_esg = "ESG_type" in keys or "esg_type" in keys
        mis = sum(1 for r in rows if "islead" in str(r.get("evidence_quality")))
        mis_total += mis
        totals[lang] = rows
        A("| %s | %d | %d | **%d** | %s | %s | %s | %d |"
          % (lang, ntr, nte, len(rows),
             "yes" if has_data else "**NO**",
             "yes" if has_span else "no",
             "yes" if has_esg else "no", mis))
    A("")
    A("**Total Misleading across all five languages: %d.** The paper's Table 1 "
      "reports 10; the released data contains more." % mis_total)
    A("")
    A("Consequences:")
    A("")
    A("- **Chinese and Korean ship no paragraph text.** They cannot be used for "
      "classification or extraction without first re-extracting the page text "
      "from the source PDFs (Chinese PDFs are provided in the same Drive folder).")
    A("- **Japanese is the only language with the full VeriPromiseESG4K schema** "
      "(`data` + spans + ESG type) and it holds the majority of the Misleading "
      "instances.")
    A("- English and French have text but no span annotations, so they support "
      "classification transfer only.")
    A("")

    # ---- Chinese detail ----
    zh = totals.get("Chinese", [])
    A("## 2. Chinese subset detail")
    A("")
    pyes = [r for r in zh if r["promise_status"] == "Yes"]
    tl = Counter(r["verification_timeline"] for r in pyes)
    real = sum(v for k, v in tl.items() if k != "N/A")
    A("- Released instances: **%d** (paper Section 3.4 states 610; Table 1's "
      "Promise-Identification row totals 199)." % len(zh))
    A("- `promise_status=Yes`: %d (%.1f%%)" % (len(pyes), 100.0 * len(pyes) / len(zh)))
    A("- Label vocabulary differs from VeriPromiseESG4K: "
      "`Less than 2 years` / `2 to 5 years` / `More than 5 years` / `N/A`, and "
      "`Potentially Misleading` rather than `Misleading`.")
    A("- **There is no `already` class.** `N/A` covers both 'no promise' and "
      "'already verified'. Among promise-bearing instances `N/A` is %d/%d = "
      "**%.1f%%**, against `already` = 44.1%% in VeriPromiseESG4K -- close enough "
      "that the two classes are comparable."
      % (tl["N/A"], len(pyes), 100.0 * tl["N/A"] / len(pyes)))
    A("")
    A("| Timing (given promise=Yes) | ML-Promise ZH | VeriPromiseESG4K |")
    A("|---|---:|---:|")
    A("| within 2 years | %d (%.1f%%) | 34 (2.1%%) |"
      % (tl["Less than 2 years"], 100.0 * tl["Less than 2 years"] / len(pyes)))
    A("| 2 to 5 years | %d (%.1f%%) | 498 (30.6%%) |"
      % (tl["2 to 5 years"], 100.0 * tl["2 to 5 years"] / len(pyes)))
    A("| more than 5 years | %d (%.1f%%) | 377 (23.2%%) |"
      % (tl["More than 5 years"], 100.0 * tl["More than 5 years"] / len(pyes)))
    A("| N/A -- already | %d (%.1f%%) | 718 (44.1%%) |"
      % (tl["N/A"], 100.0 * tl["N/A"] / len(pyes)))
    A("")
    A("Renormalised over the three real horizons: within-2-years is "
      "**%.1f%%** here (n=%d) against **3.7%%** in VeriPromiseESG4K. This "
      "reproduces the Section 1 finding on the released data rather than on "
      "transcribed percentages." % (100.0 * tl["Less than 2 years"] / real, real))
    A("")

    # ---- company overlap ----
    A("## 3. Company overlap with VeriPromiseESG4K")
    A("")
    A("This is the control that isolates annotator drift from corpus content: "
      "the same company, annotated twice by different teams.")
    A("")
    vp = load_vpesg()
    vp_by_ticker = Counter(str(r["ticker"]).strip() for r in vp)
    zh_by_pdf = Counter(r.get("pdf") for r in zh)
    A("| ML-Promise PDF | ML-Promise n | TWSE ticker | VeriPromiseESG4K n (labelled) |")
    A("|---|---:|---|---:|")
    ov_mlp = ov_vp = 0
    for pdf, n in zh_by_pdf.most_common():
        t = PDF_TO_TICKER.get(pdf)
        if t:
            ov_mlp += n
            ov_vp += vp_by_ticker.get(t, 0)
            A("| %s | %d | `%s` | %d |" % (pdf, n, t, vp_by_ticker.get(t, 0)))
        else:
            A("| %s | %d | -- | -- |" % (pdf, n))
    A("")
    A("**%d of %d ML-Promise Chinese instances (%.0f%%) come from companies that "
      "also appear in VeriPromiseESG4K**, matched by %d labelled instances on the "
      "VeriPromiseESG4K side."
      % (ov_mlp, len(zh), 100.0 * ov_mlp / len(zh), ov_vp))
    A("")
    A("Caveat: the report years differ. ML-Promise uses 2022-2023 reports "
      "(e.g. the TSMC URL points at `2022_sustainabilityReport`) while "
      "VeriPromiseESG4K uses 2024 reports. Company is held constant, document is "
      "not.")
    A("")
    A("The released Chinese set covers **10** source PDFs, not the 9 companies "
      "per country described in the paper.")
    A("")

    # ---- extraction baselines worth beating ----
    A("## 4. Published extraction baselines (ML-Promise Table 6, Chinese)")
    A("")
    A("| Input | RAG | Promise Extraction | Evidence Extraction |")
    A("|---|---|---:|---:|")
    A("| Text | no | 0.012 | 0.007 |")
    A("| Text | yes | 0.101 | 0.139 |")
    A("| Image | no | 0.190 | 0.230 |")
    A("| Image | yes | 0.240 | 0.317 |")
    A("")
    A("ROUGE-L, GPT-4o with E5/E5-V retrieval. These are weak, and span "
      "annotations are present for 100% of the positive instances in both "
      "corpora. Note that beating a zero/few-shot LLM with a fine-tuned model is "
      "not a like-for-like comparison -- a matched LLM baseline has to be run on "
      "VeriPromiseESG4K as well.")
    A("")

    dest = os.path.join(OUT, "mlpromise_inventory.md")
    open(dest, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote", dest)


if __name__ == "__main__":
    main()
