"""E3: does conditioning on the gold evidence span help evidence_quality?

This is the go/no-go for the locate-then-judge hypothesis. If feeding the model
the gold `evidence_string` instead of the whole paragraph does not improve
evidence_quality, then the reformulation cannot be the fix, regardless of how
good a span extractor we build.

Conditions (all predict evidence_quality on rows where evidence_status = Yes):

  A  full paragraph                     -- the current formulation
  B  gold evidence_string only          -- the span-conditioning upper bound
  C  gold promise_string + evidence_string -- the paired formulation
  D  length-matched random substring    -- control: is any gain just from
                                           shorter input rather than the *right*
                                           span?

Condition D matters. Without it, a gain in B could be explained by shorter,
lower-variance inputs rather than by the span carrying the signal.

Model: character n-gram TF-IDF + linear SVM. This needs no model download,
which the current disk situation requires. It is a *directional* probe, not an
absolute upper bound: a bag-of-character-ngrams model cannot represent the
promise-evidence relation, so it likely understates what a cross-encoder would
gain from condition C in particular. Read the ordering, not the absolute
numbers.

Train: official train + val. Test: official test. All gold, from v1.0.
"""
import csv
import io
import os
import random
import sys
from collections import Counter

import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.svm import LinearSVC
from sklearn.metrics import f1_score, classification_report
from sklearn.pipeline import make_pipeline

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "data", "veripromiseesgdataset")
OUT = os.path.join(ROOT, "research", "output")
os.makedirs(OUT, exist_ok=True)

SEED = 20260823
CLASSES = ["Clear", "Not Clear", "Misleading"]
N_BOOT = 1000


def load(fn):
    return list(csv.DictReader(open(os.path.join(D, fn), encoding="utf-8-sig")))


def span_ok(v):
    return (v or "").strip() not in ("", "N/A")


def build(rows, rng):
    """Return the four input variants plus the label, for evidence=Yes rows."""
    out = []
    for r in rows:
        if r["evidence_status"] != "Yes":
            continue
        q = (r["evidence_quality"] or "").strip()
        if q not in CLASSES:
            continue
        para = r["data"] or ""
        ev = r["evidence_string"].strip() if span_ok(r["evidence_string"]) else ""
        pr = r["promise_string"].strip() if span_ok(r["promise_string"]) else ""
        if not ev:
            continue
        n = len(ev)
        if len(para) > n:
            s = rng.randrange(0, len(para) - n)
            rand = para[s:s + n]
        else:
            rand = para
        out.append({
            "A_paragraph": para,
            "B_evidence_span": ev,
            "C_promise_plus_evidence": (pr + " [SEP] " + ev) if pr else ev,
            "D_length_matched_random": rand,
            "y": q,
            "id": r["id"],
        })
    return out


def evaluate(train, test, key):
    vec = TfidfVectorizer(analyzer="char_wb", ngram_range=(1, 3),
                          min_df=2, sublinear_tf=True, max_features=200000)
    clf = LinearSVC(C=1.0, class_weight="balanced", random_state=SEED, max_iter=5000)
    pipe = make_pipeline(vec, clf)
    pipe.fit([r[key] for r in train], [r["y"] for r in train])
    pred = pipe.predict([r[key] for r in test])
    gold = [r["y"] for r in test]
    macro = f1_score(gold, pred, labels=CLASSES, average="macro", zero_division=0)
    per = {c: f1_score(gold, pred, labels=[c], average="macro", zero_division=0)
           for c in CLASSES}
    return macro, per, pred, gold


def boot_ci(gold, pred_a, pred_b, rng):
    """Bootstrap CI for macroF1(b) - macroF1(a)."""
    n = len(gold)
    g = np.array(gold, dtype=object)
    a = np.array(pred_a, dtype=object)
    b = np.array(pred_b, dtype=object)
    d = []
    for _ in range(N_BOOT):
        idx = rng.integers(0, n, n)
        d.append(f1_score(g[idx], b[idx], labels=CLASSES, average="macro", zero_division=0)
                 - f1_score(g[idx], a[idx], labels=CLASSES, average="macro", zero_division=0))
    return float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))


def main():
    rng = random.Random(SEED)
    train = build(load("vpesg4k_train_1000") + load("vpesg4k_val_1000"), rng)
    test = build(load("vpesg4k_test_2000.csv"), rng)

    L = []
    A = L.append
    A("# E3: gold-span upper bound for `evidence_quality`")
    A("")
    A("Generated by `research/scripts/07_e3_gold_span_upper_bound.py`.")
    A("")
    A("Go/no-go for locate-then-judge. If feeding the gold `evidence_string` "
      "instead of the paragraph does not help, the reformulation cannot be the "
      "fix no matter how good a span extractor we build.")
    A("")
    A("Train %d / test %d instances (rows with `evidence_status=Yes` and a "
      "usable gold evidence span)." % (len(train), len(test)))
    A("")
    A("Label counts -- train %s, test %s."
      % (dict(Counter(r["y"] for r in train)), dict(Counter(r["y"] for r in test))))
    A("")
    A("**Model: character n-gram TF-IDF + linear SVM.** No model download, which "
      "the current disk situation requires. This is a *directional probe*, not an "
      "absolute upper bound -- a bag-of-character-ngrams model cannot represent "
      "the promise-evidence relation, so it probably understates condition C. "
      "Read the ordering, not the absolute numbers.")
    A("")

    keys = [("A_paragraph", "A. full paragraph (current formulation)"),
            ("B_evidence_span", "B. gold evidence span only"),
            ("C_promise_plus_evidence", "C. gold promise + evidence span"),
            ("D_length_matched_random", "D. length-matched random substring (control)")]

    A("| condition | macro-F1 | Clear | Not Clear | Misleading | mean input chars |")
    A("|---|---:|---:|---:|---:|---:|")
    res = {}
    for k, label in keys:
        macro, per, pred, gold = evaluate(train, test, k)
        res[k] = (macro, pred, gold)
        mlen = np.mean([len(r[k]) for r in test])
        A("| %s | **%.4f** | %.4f | %.4f | %.4f | %.0f |"
          % (label, macro, per["Clear"], per["Not Clear"], per["Misleading"], mlen))
    A("")

    nrng = np.random.default_rng(SEED)
    base_macro, base_pred, gold = res["A_paragraph"]
    A("| comparison | delta macro-F1 | bootstrap 95% CI |")
    A("|---|---:|---|")
    for k, label in keys[1:]:
        m, p, _ = res[k]
        lo, hi = boot_ci(gold, base_pred, p, nrng)
        A("| %s vs A | %+.4f | [%+.4f, %+.4f] |" % (label.split(".")[0], m - base_macro, lo, hi))
    A("")

    # ---- how weak is the probe? compare against the tuned ensemble ----
    sub = {r["id"] for r in test}
    gold_map = {r["id"]: r for r in load("vpesg4k_test_2000.csv")}
    ens = {r["id"]: r for r in csv.DictReader(
        open(os.path.join(ROOT, "submissions", "ens_3way_tuned.csv"),
             encoding="utf-8-sig"))}
    ids = sorted(sub)
    gy = [gold_map[i]["evidence_quality"] for i in ids]
    py = [ens[i]["evidence_quality"] for i in ids]
    ens_macro = f1_score(gy, py, labels=CLASSES, average="macro", zero_division=0)
    A("## How weak is this probe?")
    A("")
    A("| model | macro-F1 | Clear | Not Clear | Misleading |")
    A("|---|---:|---:|---:|---:|")
    A("| TF-IDF probe, condition A | %.4f | %.4f | %.4f | %.4f |"
      % (base_macro,
         f1_score(gold, base_pred, labels=["Clear"], average="macro", zero_division=0),
         f1_score(gold, base_pred, labels=["Not Clear"], average="macro", zero_division=0),
         f1_score(gold, base_pred, labels=["Misleading"], average="macro", zero_division=0)))
    A("| our transformer ensemble | %.4f | %.4f | %.4f | %.4f |"
      % (ens_macro,
         f1_score(gy, py, labels=["Clear"], average="macro", zero_division=0),
         f1_score(gy, py, labels=["Not Clear"], average="macro", zero_division=0),
         f1_score(gy, py, labels=["Misleading"], average="macro", zero_division=0)))
    A("")
    A("The probe trails the transformer by %.4f overall, and **the entire gap is "
      "in `Not Clear`** -- exactly the class that carries the difficulty. A "
      "bag-of-character-ngrams model is therefore weakest precisely where the "
      "span-conditioning effect would have to show up, so this run cannot reject "
      "the hypothesis on its own." % (ens_macro - base_macro))
    A("")

    A("## Reading")
    A("")
    b = res["B_evidence_span"][0] - base_macro
    c = res["C_promise_plus_evidence"][0] - base_macro
    d = res["D_length_matched_random"][0] - base_macro
    A("- B - A = %+.4f, C - A = %+.4f, D - A = %+.4f." % (b, c, d))
    A("- The control D is the key comparison. If B beats A by roughly the same "
      "margin as D does, the gain is from shorter input rather than from the "
      "span being the *right* text, and the locate-then-judge story does not "
      "hold.")
    A("")

    dest = os.path.join(OUT, "e3_gold_span_upper_bound.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", dest)
    print()
    print("\n".join(L))


if __name__ == "__main__":
    main()
