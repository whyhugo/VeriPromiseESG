"""How much of the paragraph do the gold spans actually cover?

This is the go/no-go check for the locate-then-judge hypothesis. That hypothesis
says evidence_quality is hard because the model is asked to judge a whole
paragraph when the judgement really concerns one span. If the span is most of
the paragraph, conditioning on it cannot help much.

Also measures how many spans can be recovered from the paragraph by exact
string match, which determines how much fuzzy alignment work a span model needs.
"""
import csv
import io
import os
import re
import statistics
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "data", "veripromiseesgdataset")
OUT = os.path.join(ROOT, "research", "output")
os.makedirs(OUT, exist_ok=True)

FILES = ["vpesg4k_train_1000", "vpesg4k_val_1000", "vpesg4k_test_2000.csv"]


def strip_ws(s):
    return re.sub(r"\s+", "", s or "")


def main():
    rows = []
    for f in FILES:
        rows += list(csv.DictReader(open(os.path.join(D, f), encoding="utf-8-sig")))

    L = []
    A = L.append
    A("# Gold span coverage in VeriPromiseESG4K")
    A("")
    A("Generated by `research/scripts/06_span_coverage.py` over all %d instances "
      "(train + val + test, gold labels released in v1.0)." % len(rows))
    A("")
    A("| span | n | exact match | after whitespace norm | median share of paragraph | mean |")
    A("|---|---:|---:|---:|---:|---:|")

    stats = {}
    for fld, cond in [("promise_string", "promise_status"),
                      ("evidence_string", "evidence_status")]:
        sub = [r for r in rows
               if r[cond] == "Yes" and r[fld].strip() not in ("", "N/A")]
        exact = sum(1 for r in sub if r[fld].strip() in r["data"])
        normd = sum(1 for r in sub if strip_ws(r[fld]) in strip_ws(r["data"]))
        cov = [min(1.0, len(strip_ws(r[fld])) / max(1, len(strip_ws(r["data"]))))
               for r in sub]
        stats[fld] = cov
        A("| `%s` | %d | %d (%.1f%%) | %d (%.1f%%) | %.1f%% | %.1f%% |"
          % (fld, len(sub), exact, 100.0 * exact / len(sub),
             normd, 100.0 * normd / len(sub),
             statistics.median(cov) * 100, statistics.mean(cov) * 100))
    A("")

    A("Share-of-paragraph distribution:")
    A("")
    A("| span | >=90% | >=70% | >=50% | >=30% |")
    A("|---|---:|---:|---:|---:|")
    for fld, cov in stats.items():
        A("| `%s` | %.1f%% | %.1f%% | %.1f%% | %.1f%% |"
          % (fld, *[100.0 * sum(1 for c in cov if c >= t) / len(cov)
                    for t in (0.9, 0.7, 0.5, 0.3)]))
    A("")

    both = [r for r in rows
            if r["promise_status"] == "Yes" and r["evidence_status"] == "Yes"
            and r["promise_string"].strip() not in ("", "N/A")
            and r["evidence_string"].strip() not in ("", "N/A")]
    comb = [min(1.0, (len(strip_ws(r["promise_string"]))
                      + len(strip_ws(r["evidence_string"])))
                / max(1, len(strip_ws(r["data"])))) for r in both]
    A("Promise and evidence spans combined (n=%d): median **%.1f%%** of the "
      "paragraph, and **%.1f%%** of instances have the two spans covering 80%% "
      "or more."
      % (len(both), statistics.median(comb) * 100,
         100.0 * sum(1 for c in comb if c >= 0.8) / len(comb)))
    A("")
    A("## Reading")
    A("")
    A("- For `evidence_quality`, the relevant span is `evidence_string`, which is "
      "a **median 52%% of the paragraph**. Conditioning on it discards roughly "
      "half the input, not the great majority. The locate-then-judge hypothesis "
      "is therefore *plausible but not obviously decisive*, and has to be settled "
      "by the gold-span upper-bound experiment rather than argued from coverage.")
    A("- Roughly a quarter of spans cannot be recovered by exact match, and "
      "whitespace normalisation barely helps (+0.6 to +0.9 points), so the "
      "mismatch is not just spacing. Any span model needs fuzzy alignment, and "
      "the alignment failure rate is itself worth reporting.")
    A("")

    dest = os.path.join(OUT, "span_coverage.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", dest)


if __name__ == "__main__":
    main()
