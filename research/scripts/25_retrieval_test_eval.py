"""The retrieval gain, measured once on the official test set.

Stage A produced the first honest gain in this project: mixing a
similarity-weighted neighbour vote into the encoder lifts verification_timeline
by +0.0253 out of sample. Two things said it was not the noise-fitting that
killed the LLM vote -- the oracle ceiling was +0.0283, only 0.003 above it, and
the two stratified halves fitted weights of 0.50 and 0.35 rather than differing
sixfold.

Both of those were still measured on train+val. This runs the protocol that
turns it into a claim:

  1. fit the mixing weight on train+val, using the encoder's out-of-fold
     probabilities and leave-one-out retrieval, exactly as a deployed system
     would have to
  2. on test, retrieve from train+val -- a genuine cross-set lookup, no
     leave-one-out needed since the query is not in the pool
  3. score the test set once

The encoder's test probabilities come from the same five-fold run that produced
its out-of-fold ones (script 18), so the two sides of the mixture are matched.

Also reports what the retrieval adds to each class, since a gain concentrated in
the majority class would mean something different from one spread across the
rare ones.
"""
import csv
import io
import json
import os
import sys

import numpy as np
import torch
from sklearn.metrics import classification_report, f1_score

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "data", "veripromiseesgdataset")
OUT = os.path.join(ROOT, "research", "output")
S18 = os.path.join(ROOT, "research", "artifacts", "s18")
S23 = os.path.join(ROOT, "research", "artifacts", "s23")
os.makedirs(OUT, exist_ok=True)
SEED = 20260824

LABELS = {
    "promise_status": ["No", "Yes"],
    "evidence_status": ["N/A", "No", "Yes"],
    "evidence_quality": ["N/A", "Not Clear", "Clear", "Misleading"],
    "verification_timeline": ["N/A", "already", "within_2_years",
                              "between_2_and_5_years", "more_than_5_years"],
}
COMP_W = {"promise_status": 0.20, "evidence_status": 0.30,
          "evidence_quality": 0.35, "verification_timeline": 0.15}
WEIGHTS = np.arange(0.0, 0.81, 0.05)
KS = [1, 3, 5, 10, 20]
EMBED_MODEL = "BAAI/bge-m3"


def load(fn):
    return list(csv.DictReader(open(os.path.join(D, fn), encoding="utf-8-sig")))


def na(v):
    v = (v or "").strip()
    return "N/A" if v in ("", "N/A") else v


def macro(y, p):
    return f1_score(y, p, average="macro", zero_division=0)


def embed(texts, tag, bs=16):
    cf = os.path.join(S23, "emb_%s.npy" % tag)
    if os.path.exists(cf):
        e = np.load(cf)
        if len(e) == len(texts):
            print("[cached] %s %s" % (tag, e.shape), flush=True)
            return e
    from sentence_transformers import SentenceTransformer
    m = SentenceTransformer(EMBED_MODEL, device="cuda")
    e = m.encode(texts, batch_size=bs, normalize_embeddings=True,
                 show_progress_bar=False, convert_to_numpy=True)
    del m
    torch.cuda.empty_cache()
    np.save(cf, e)
    print("embedded %s %s" % (tag, e.shape), flush=True)
    return e


def knn_prob(sim, y_pool, k, nlab):
    idx = np.argpartition(-sim, k, axis=1)[:, :k]
    out = np.zeros((sim.shape[0], nlab))
    for i in range(sim.shape[0]):
        nb = idx[i]
        np.add.at(out[i], y_pool[nb], np.clip(sim[i, nb], 0.0, None))
    return out / np.maximum(out.sum(1, keepdims=True), 1e-9)


def main():
    trv = load("vpesg4k_train_1000") + load("vpesg4k_val_1000")
    te = load("vpesg4k_test_2000.csv")

    e_trv = np.load(os.path.join(S23, "emb.npy"))
    if len(e_trv) != len(trv):
        e_trv = embed([r["data"] or "" for r in trv], "trv")
    e_te = embed([r["data"] or "" for r in te], "test")

    sim_loo = e_trv @ e_trv.T
    np.fill_diagonal(sim_loo, -1.0)
    sim_te = e_te @ e_trv.T            # cross-set: test queries, train+val pool

    L = []
    A = L.append
    A("# The retrieval gain on the official test set")
    A("")
    A("Generated by `research/scripts/25_retrieval_test_eval.py`. Both `k` and "
      "the mixing weight are chosen on train+val only, using out-of-fold encoder "
      "probabilities and leave-one-out retrieval. Test rows retrieve from "
      "train+val, and the test set is scored once.")
    A("")
    A("| subtask | chosen k | chosen w | encoder (test) | **+ retrieval (test)** | delta |")
    A("|---|---:|---:|---:|---:|---:|")

    chosen, per_class = {}, {}
    tot_base = tot_new = 0.0
    for f in LABELS:
        nlab = len(LABELS[f])
        y_trv = np.array([LABELS[f].index(na(r[f])) for r in trv])
        y_te = np.array([LABELS[f].index(na(r[f])) for r in te])
        z = np.load(os.path.join(S18, "%s.npz" % f.replace("_", "")))
        eo, et = z["oof"], z["test"]

        # pick k and w together on train+val
        best = (-1e9, None, None)
        for k in KS:
            kp = knn_prob(sim_loo, y_trv, k, nlab)
            for w in WEIGHTS:
                s = macro(y_trv, ((1 - w) * eo + w * kp).argmax(1))
                if s > best[0]:
                    best = (s, k, w)
        _, k, w = best
        chosen[f] = (k, w)

        kp_te = knn_prob(sim_te, y_trv, k, nlab)
        base = macro(y_te, et.argmax(1))
        new = macro(y_te, ((1 - w) * et + w * kp_te).argmax(1))
        tot_base += COMP_W[f] * base
        tot_new += COMP_W[f] * new
        per_class[f] = (y_te, et.argmax(1), ((1 - w) * et + w * kp_te).argmax(1))
        A("| `%s` | %d | %.2f | %.4f | **%.4f** | %+.4f |"
          % (f, k, w, base, new, new - base))
        print("[%s] k=%d w=%.2f  %.4f -> %.4f" % (f, k, w, base, new), flush=True)

    A("")
    A("| | 加權總計 |")
    A("|---|---:|")
    A("| encoder alone | %.4f |" % tot_base)
    A("| **+ retrieval** | **%.4f** |" % tot_new)
    A("| delta | **%+.4f** |" % (tot_new - tot_base))
    A("")
    A("The competition ensemble scores 0.6384 on the same metric with three "
      "backbones and a fifteen-epoch budget; the encoder here is one backbone "
      "at four epochs, so the comparison that matters is the delta, not the "
      "absolute.")
    A("")

    A("## Where the gain lands, `verification_timeline`")
    A("")
    y, pb, pn = per_class["verification_timeline"]
    labs = LABELS["verification_timeline"]
    rb = classification_report(y, pb, labels=range(len(labs)), target_names=labs,
                               output_dict=True, zero_division=0)
    rn = classification_report(y, pn, labels=range(len(labs)), target_names=labs,
                               output_dict=True, zero_division=0)
    A("| class | test n | encoder F1 | + retrieval F1 | delta |")
    A("|---|---:|---:|---:|---:|")
    for c in labs:
        A("| `%s` | %d | %.4f | %.4f | %+.4f |"
          % (c, int(rb[c]["support"]), rb[c]["f1-score"], rn[c]["f1-score"],
             rn[c]["f1-score"] - rb[c]["f1-score"]))
    A("")

    json.dump({f: {"k": int(v[0]), "w": float(v[1])} for f, v in chosen.items()},
              open(os.path.join(S23, "chosen.json"), "w"), indent=1)
    dest = os.path.join(OUT, "retrieval_test_eval.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", dest, flush=True)
    print("\n".join(L))


if __name__ == "__main__":
    main()
