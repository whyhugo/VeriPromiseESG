"""Is the disputed-versus-control difference just the models' own verdict?

Script 35 reported that the disputed paragraphs draw far more "missing figures"
reasons than the control paragraphs, with a vanishing p-value. The two groups
are not comparable in the way that comparison assumes: a control row is one
where the models matched the annotators, and since most gold labels are `Clear`,
most control rows are rows the models called `Clear`. A disputed row is mostly
one they called `Not Clear`. So the contrast may be measuring nothing but "a
model that answers `Not Clear` says figures are missing", which is close to a
tautology.

This holds the models' own verdict fixed and asks whether anything is left. It
also checks the quantity script 49 uses instead -- the co-occurrence of the
stated vagueness criterion with missing figures -- against the same
stratification, since a mechanism claim is only worth making if it survives it.

CPU only; groups come from `probe_groups.py`.
"""
import importlib.util
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
_keep = sys.stdout
_spec = importlib.util.spec_from_file_location(
    "probe_groups", os.path.join(HERE, "probe_groups.py"))
pg = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(pg)
_keep2 = sys.stdout

OUT = os.path.join(ROOT, "research", "output")
os.makedirs(OUT, exist_ok=True)
FIG = "unstated: no concrete figures"
VAG = "stated: vague wording"


def main():
    g = pg.groups()
    s35 = g["s35"]
    verdict, models, reasons = g["verdict"], g["models"], g["reasons"]
    ctrl, wrong = g["control"], g["disputed"]

    def texts(ids):
        return [reasons[m][i][1] for m in reasons for i in ids
                if i in reasons[m] and reasons[m][i][1]]

    L = []
    A = L.append
    A("# Does the disputed-versus-control contrast survive its own confound?")
    A("")
    A("Generated by `research/scripts/48_verdict_stratified_check.py`. "
      + pg.provenance(g))
    A("")

    A("## The confound, stated as a count")
    A("")
    A("| group | rows | models said Clear | said Not Clear | said something else |")
    A("|---|---:|---:|---:|---:|")
    for name, grp in (("control", ctrl), ("disputed", wrong)):
        c = sum(1 for i in grp if verdict[models[0]][i] == "Clear")
        n = sum(1 for i in grp if verdict[models[0]][i] == "Not Clear")
        A("| %s | %d | %d | %d | %d |" % (name, len(grp), c, n, len(grp) - c - n))
    A("")
    A("The two groups differ in their verdict mix by construction, so any rate "
      "that depends on the verdict will differ between them for that reason "
      "alone.")
    A("")

    A("## Holding the verdict fixed")
    A("")
    A("| stratum | reasons | cites missing figures | cites vague wording |")
    A("|---|---:|---:|---:|")
    for name, grp in (("control", ctrl), ("disputed", wrong)):
        for v in ["Clear", "Not Clear"]:
            rs = texts([i for i in grp if verdict[models[0]][i] == v])
            if not rs:
                continue
            A("| %s / models said %s | %d | %.3f | %.3f |"
              % (name, v, len(rs),
                 float(np.mean([FIG in s35.code(r) for r in rs])),
                 float(np.mean([VAG in s35.code(r) for r in rs]))))
    A("")
    A("Within a verdict the two groups are close, and the ordering is not even "
      "consistent. **The headline contrast is a verdict-composition effect and "
      "this project does not use it.**")
    A("")

    A("## The quantity that does survive")
    A("")
    A("Co-occurrence: among reasons that call a paragraph vague, the share that "
      "also name missing figures. Script 49 reports it in full; this is the "
      "same stratification applied to it.")
    A("")
    A("| stratum | reasons calling it vague | of those, also naming figures |")
    A("|---|---:|---:|")
    for name, grp in (("control", ctrl), ("disputed", wrong)):
        for v in [None, "Clear", "Not Clear"]:
            sub = grp if v is None else [i for i in grp
                                         if verdict[models[0]][i] == v]
            vg = [r for r in texts(sub) if VAG in s35.code(r)]
            if len(vg) < 10:
                continue
            A("| %s / %s | %d | %.3f |"
              % (name, v or "all verdicts", len(vg),
                 float(np.mean([FIG in s35.code(r) for r in vg]))))
    A("")
    A("This one does not move with the stratification, which is why it and not "
      "the group contrast carries the mechanism claim.")
    A("")
    dest = os.path.join(OUT, "verdict_stratified_check.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    _keep.write("wrote %s\n" % dest)
    _keep.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
