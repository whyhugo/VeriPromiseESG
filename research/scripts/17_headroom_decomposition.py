"""Where is the headroom, and is subtask 3 even the right thing to work on?

Five attempts to improve evidence_quality directly have now failed (scripts
07-14). Before a sixth, this asks where the remaining error actually lives, so
the choice of target is made from measurement rather than from the competition's
weighting.

Three oracle substitutions isolate the parts:

  oracle gate       replace evidence_status with gold, keep the quality model
  oracle judgement  replace the Clear/Not Clear/Misleading call with gold, keep
                    the model's gate
  oracle Misleading only the three Misleading rows are given to the model

Each is an upper bound on what perfecting that component could buy. Comparing
them says whether evidence_quality is limited by upstream gating, by the
judgement itself, or by the degenerate class -- and therefore whether to keep
attacking subtask 3 or to move to a subtask where the headroom is reachable.

Also reports, for every subtask, how much of its macro-F1 rests on its rarest
class, and how far each sits from the inter-annotator ceiling. Scored with the
independent framework of script 16, not the competition formula.
"""
import csv
import io
import os
import sys
from collections import Counter

import numpy as np
from sklearn.metrics import (balanced_accuracy_score, f1_score,
                             precision_recall_fscore_support)

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "data", "veripromiseesgdataset")
SUBS = os.path.join(ROOT, "submissions")
OUT = os.path.join(ROOT, "research", "output")
os.makedirs(OUT, exist_ok=True)

FIELDS = ["promise_status", "evidence_status", "evidence_quality",
          "verification_timeline"]
HUMAN_ALPHA = {"promise_status": 0.977, "evidence_status": 0.962,
               "evidence_quality": 0.940, "verification_timeline": 0.955}
EQ, ES, PS, VT = ("evidence_quality", "evidence_status", "promise_status",
                  "verification_timeline")


def na(v):
    v = (v or "").strip()
    return "N/A" if v in ("", "N/A") else v


def main():
    gold = {r["id"]: r for r in csv.DictReader(
        open(os.path.join(D, "vpesg4k_test_2000.csv"), encoding="utf-8-sig"))}
    pred = {r["id"]: r for r in csv.DictReader(
        open(os.path.join(SUBS, "ens_3way_tuned.csv"), encoding="utf-8-sig"))}
    ids = sorted(gold)
    y = [na(gold[i][EQ]) for i in ids]
    labs = sorted(set(y))

    def mf(pr):
        return f1_score(y, pr, labels=labs, average="macro", zero_division=0)

    cur = [na(pred[i][EQ]) for i in ids]
    base = mf(cur)

    o_gate = ["N/A" if na(gold[i][ES]) != "Yes"
              else (na(pred[i][EQ]) if na(pred[i][EQ]) != "N/A" else "Clear")
              for i in ids]
    o_judge = ["N/A" if na(pred[i][ES]) != "Yes"
               else (na(gold[i][EQ]) if na(gold[i][EQ]) != "N/A" else "Clear")
               for i in ids]
    o_mis = [na(gold[i][EQ]) if na(gold[i][EQ]) == "Misleading" else na(pred[i][EQ])
             for i in ids]
    o_both = [na(gold[i][EQ]) for i in ids]

    L = []
    A = L.append
    A("# Where the headroom is")
    A("")
    A("Generated by `research/scripts/17_headroom_decomposition.py` on the "
      "official 2,000-row test set, scored with the independent framework of "
      "script 16 rather than the competition formula.")
    A("")
    A("## Oracle decomposition of `evidence_quality`")
    A("")
    A("Each row replaces one component with the gold answer and leaves the rest "
      "of the system alone, so it upper-bounds what perfecting that component "
      "could buy.")
    A("")
    A("| system | macro-F1 | gain over current |")
    A("|---|---:|---:|")
    A("| current system | %.4f | --- |" % base)
    A("| + oracle gate (`evidence_status` from gold) | %.4f | **%+.4f** |"
      % (mf(o_gate), mf(o_gate) - base))
    A("| + oracle Misleading (3 rows handed to the model) | %.4f | **%+.4f** |"
      % (mf(o_mis), mf(o_mis) - base))
    A("| + oracle judgement (Clear/Not Clear/Misleading from gold) | %.4f | %+.4f |"
      % (mf(o_judge), mf(o_judge) - base))
    A("| perfect | %.4f | %+.4f |" % (mf(o_both), mf(o_both) - base))
    A("")
    mis_only = mf(o_mis) - base
    judge_rest = (mf(o_judge) - base) - mis_only
    A("Reading the judgement row against the Misleading row separates them: of "
      "the %+.4f available from a perfect judgement, **%+.4f is the three "
      "Misleading rows alone** and only %+.4f is everything else -- all 1,332 "
      "Clear and Not Clear decisions combined."
      % (mf(o_judge) - base, mis_only, judge_rest))
    A("")
    A("So the three components rank: Misleading %+.4f, gate %+.4f, the rest of "
      "the judgement %+.4f. The largest single lever is the one class that "
      "scripts 09 and 11 showed to be undetectable by any method we have."
      % (mis_only, mf(o_gate) - base, judge_rest))
    A("")

    A("## What limits the gate")
    A("")
    A("`evidence_status` confusion matrix, rows gold, columns predicted:")
    A("")
    cats = ["N/A", "No", "Yes"]
    M = Counter((na(gold[i][ES]), na(pred[i][ES])) for i in ids)
    A("| gold \\ pred | %s | total |" % " | ".join(cats))
    A("|---|%s---:|" % ("---:|" * len(cats)))
    for a in cats:
        row = [M[(a, b)] for b in cats]
        A("| **%s** | %s | %d |" % (a, " | ".join(str(v) for v in row), sum(row)))
    A("")
    yes_fp = M[("N/A", "Yes")] + M[("No", "Yes")]
    A("The gate fails in one direction: **%d rows are called `Yes` when no "
      "evidence exists** (%d with no promise at all, %d with a promise but no "
      "evidence). Recall on `No` is only %.3f. Every one of those rows then "
      "receives a Clear or Not Clear label that cannot be right."
      % (yes_fp, M[("N/A", "Yes")], M[("No", "Yes")],
         M[("No", "No")] / max(1, sum(M[("No", c)] for c in cats))))
    A("")

    A("## Rare-class leverage across all four subtasks")
    A("")
    A("| subtask | rarest class | test n | train+val n | its F1 | macro-F1 | without it | shift |")
    A("|---|---|---:|---:|---:|---:|---:|---:|")
    trv = (list(csv.DictReader(open(os.path.join(D, "vpesg4k_train_1000"),
                                    encoding="utf-8-sig")))
           + list(csv.DictReader(open(os.path.join(D, "vpesg4k_val_1000"),
                                      encoding="utf-8-sig"))))
    for f in FIELDS:
        yy = [na(gold[i][f]) for i in ids]
        qq = [na(pred[i][f]) for i in ids]
        cnt = Counter(yy)
        rare, n = cnt.most_common()[-1]
        ll = sorted(cnt)
        keep = [c for c in ll if c != rare]
        a = f1_score(yy, qq, labels=ll, average="macro", zero_division=0)
        b = f1_score(yy, qq, labels=keep, average="macro", zero_division=0)
        _, _, f1r, _ = precision_recall_fscore_support(yy, qq, labels=[rare],
                                                       zero_division=0)
        ntr = sum(1 for r in trv if na(r[f]) == rare)
        A("| `%s` | `%s` | %d | %d | %.4f | %.4f | %.4f | %+.4f |"
          % (f, rare, n, ntr, f1r[0], a, b, b - a))
    A("")
    A("Rarity alone is not the pathology. `within_2_years` has 34 training "
      "instances and the model still reaches F1 0.6465 on it, so removing it "
      "barely moves the average. `Misleading` has 2 training instances and F1 "
      "0.0000. Somewhere between 2 and 34 training examples the class becomes "
      "learnable, and only `Misleading` falls below it.")
    A("")

    A("## Distance to the human ceiling, by subtask")
    A("")

    def alpha(a, b):
        u = list(zip(a, b))
        n = len(u)
        do = sum(1.0 for x, yv in u if x != yv) / n
        vals = Counter()
        for x, yv in u:
            vals[x] += 1
            vals[yv] += 1
        N = 2 * n
        de = 1.0 - sum(c * (c - 1) for c in vals.values()) / (N * (N - 1))
        return 1.0 - do / de if de > 0 else float("nan")

    A("| subtask | alpha vs gold | annotators' alpha | ratio | classes |")
    A("|---|---:|---:|---:|---:|")
    for f in FIELDS:
        yy = [na(gold[i][f]) for i in ids]
        qq = [na(pred[i][f]) for i in ids]
        al = alpha(yy, qq)
        A("| `%s` | %.4f | %.3f | **%.3f** | %d |"
          % (f, al, HUMAN_ALPHA[f], al / HUMAN_ALPHA[f], len(set(yy))))
    A("")
    A("No subtask reaches two thirds of the agreement the annotators reached "
      "with each other, so there is headroom everywhere. On this scale "
      "`evidence_quality` and `verification_timeline` are close together "
      "(0.530 and 0.547), which the competition macro-F1 hides by scoring them "
      "0.4642 and 0.6545.")
    A("")

    A("## Implication for what to work on")
    A("")
    A("The reachable headroom in `evidence_quality` is %+.4f from the gate and "
      "%+.4f from the Clear/Not Clear judgement; the remaining %+.4f sits in "
      "three rows that nothing we have can find. Since five direct attempts on "
      "the judgement have failed, the gate is the part still worth attacking, "
      "and its failure mode is specific and learnable: recall %.3f on "
      "`evidence_status = No`, a class with %d training instances."
      % (mf(o_gate) - base, judge_rest, mis_only,
         M[("No", "No")] / max(1, sum(M[("No", c)] for c in cats)),
         sum(1 for r in trv if na(r[ES]) == "No")))
    A("")

    dest = os.path.join(OUT, "headroom_decomposition.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", dest, flush=True)
    print("\n".join(L))


if __name__ == "__main__":
    main()
