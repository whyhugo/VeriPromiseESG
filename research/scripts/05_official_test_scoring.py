"""Score submissions against the now-released VeriPromiseESG4K gold test labels.

The v1.0 dataset release (github.com/veripromiseesg/veripromiseesgdataset) ships
gold labels AND gold spans for all 4,000 instances, including the 2,000 official
test instances. That removes the constraint that shaped the earlier evaluation
plan: results can now be reported on the official test set directly.

Official metric (README):
    total = 0.20*MacroF1(promise_status)
          + 0.30*MacroF1(evidence_status)
          + 0.35*MacroF1(evidence_quality)
          + 0.15*MacroF1(verification_timeline)

This script reports, per submission:
  * the official score and its four components
  * per-class F1 for evidence_quality, isolating what the Misleading class costs
  * a counterfactual score with Misleading excluded from the macro average
  * the structural-consistency rate (SCR) against the annotation hierarchy
and does the same for the gold labels themselves as a sanity check.
"""
import csv
import io
import os
import sys
from collections import Counter

from sklearn.metrics import f1_score, classification_report

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GOLD = os.path.join(ROOT, "data", "veripromiseesgdataset", "vpesg4k_test_2000.csv")
SUBS = os.path.join(ROOT, "submissions")
OUT = os.path.join(ROOT, "research", "output")
os.makedirs(OUT, exist_ok=True)

FIELDS = [("promise_status", 0.20), ("evidence_status", 0.30),
          ("evidence_quality", 0.35), ("verification_timeline", 0.15)]


def norm(v):
    v = (v or "").strip()
    return "N/A" if v in ("", "N/A") else v


def read_csv(path):
    return list(csv.DictReader(open(path, encoding="utf-8-sig")))


def score(gold, pred):
    """Official weighted macro-F1 plus components."""
    out = {}
    total = 0.0
    for f, w in FIELDS:
        y = [norm(r[f]) for r in gold]
        p = [norm(r[f]) for r in pred]
        m = f1_score(y, p, average="macro", zero_division=0)
        out[f] = m
        total += w * m
    out["total"] = total
    return out


def scr(rows):
    """Structural consistency rate against the annotation hierarchy.

    promise=No  -> timeline, evidence_status, evidence_quality all N/A
    evidence=No -> evidence_quality N/A
    promise=Yes -> timeline and evidence_status not N/A
    evidence=Yes-> evidence_quality not N/A
    """
    bad = Counter()
    for r in rows:
        p, t = norm(r["promise_status"]), norm(r["verification_timeline"])
        e, q = norm(r["evidence_status"]), norm(r["evidence_quality"])
        v = []
        if p == "No":
            if t != "N/A":
                v.append("promise=No but timeline!=N/A")
            if e != "N/A":
                v.append("promise=No but evidence_status!=N/A")
            if q != "N/A":
                v.append("promise=No but quality!=N/A")
        else:
            if t == "N/A":
                v.append("promise=Yes but timeline=N/A")
            if e == "N/A":
                v.append("promise=Yes but evidence_status=N/A")
        if e == "No" and q != "N/A":
            v.append("evidence=No but quality!=N/A")
        if e == "Yes" and q == "N/A":
            v.append("evidence=Yes but quality=N/A")
        for x in v:
            bad[x] += 1
        if v:
            bad["_rows"] += 0
    nbad = sum(1 for r in rows if _row_bad(r))
    return nbad, bad


def _row_bad(r):
    p, t = norm(r["promise_status"]), norm(r["verification_timeline"])
    e, q = norm(r["evidence_status"]), norm(r["evidence_quality"])
    if p == "No":
        if t != "N/A" or e != "N/A" or q != "N/A":
            return True
    else:
        if t == "N/A" or e == "N/A":
            return True
    if e == "No" and q != "N/A":
        return True
    if e == "Yes" and q == "N/A":
        return True
    return False


def main():
    gold = read_csv(GOLD)
    gold_by_id = {r["id"]: r for r in gold}
    L = []
    A = L.append

    A("# Scoring against the released VeriPromiseESG4K gold test labels")
    A("")
    A("Generated by `research/scripts/05_official_test_scoring.py`.")
    A("")
    A("The v1.0 release ships gold labels and gold spans for all 4,000 instances, "
      "including the 2,000 official test instances. Official metric: "
      "`0.20*PS + 0.30*ES + 0.35*EQ + 0.15*VT`, all Macro-F1.")
    A("")

    A("## 1. Gold test-set label counts")
    A("")
    A("| field | distribution |")
    A("|---|---|")
    for f, _ in FIELDS:
        c = Counter(norm(r[f]) for r in gold)
        A("| `%s` | %s |" % (f, ", ".join("%s %d" % kv for kv in c.most_common())))
    nbad, _ = scr(gold)
    A("")
    A("Gold structural violations: **%d / %d**." % (nbad, len(gold)))
    A("")

    A("## 2. Submission scores on the official test set")
    A("")
    A("| submission | total | PS (.20) | ES (.30) | EQ (.35) | VT (.15) | SCR |")
    A("|---|---:|---:|---:|---:|---:|---:|")
    results = {}
    for fn in sorted(os.listdir(SUBS)):
        if not fn.endswith(".csv"):
            continue
        pred = read_csv(os.path.join(SUBS, fn))
        if len(pred) != len(gold):
            continue
        pred.sort(key=lambda r: int(r["id"]))
        g = [gold_by_id[r["id"]] for r in pred]
        s = score(g, pred)
        nb, _ = scr(pred)
        results[fn] = (s, g, pred)
        A("| `%s` | **%.4f** | %.4f | %.4f | %.4f | %.4f | %.1f%% |"
          % (fn, s["total"], s["promise_status"], s["evidence_status"],
             s["evidence_quality"], s["verification_timeline"],
             100.0 * (len(pred) - nb) / len(pred)))
    A("")

    best = max(results, key=lambda k: results[k][0]["total"])
    s, g, pred = results[best]
    A("## 3. What the `Misleading` class costs (`%s`)" % best)
    A("")
    y = [norm(r["evidence_quality"]) for r in g]
    p = [norm(r["evidence_quality"]) for r in pred]
    labels = ["Clear", "Not Clear", "Misleading", "N/A"]
    rep = classification_report(y, p, labels=labels, zero_division=0,
                                output_dict=True)
    A("| class | gold n | predicted n | F1 |")
    A("|---|---:|---:|---:|")
    pc = Counter(p)
    for lab in labels:
        A("| `%s` | %d | %d | %.4f |"
          % (lab, int(rep[lab]["support"]), pc.get(lab, 0), rep[lab]["f1-score"]))
    A("")
    macro_all = f1_score(y, p, average="macro", zero_division=0)
    keep = [i for i, v in enumerate(y) if v != "Misleading"]
    y3 = [y[i] for i in keep]
    p3 = [p[i] for i in keep]
    macro_3 = f1_score(y3, p3, labels=["Clear", "Not Clear", "N/A"],
                       average="macro", zero_division=0)
    nmis = int(rep["Misleading"]["support"])
    A("- `evidence_quality` Macro-F1 over all four classes: **%.4f**" % macro_all)
    A("- Same, with `Misleading` removed from both data and averaging: **%.4f**"
      % macro_3)
    A("- A system that predicted all %d `Misleading` rows perfectly would score "
      "%.4f on this task (+%.4f), worth **+%.4f on the official total**."
      % (nmis, macro_all + 0.25, 0.25, 0.35 * 0.25))
    A("")
    A("So **8.75 percentage points of the official total score are decided by %d "
      "rows out of 2,000**. For reference, the entire spread between our best and "
      "worst submission here is %.4f."
      % (nmis, max(v[0]["total"] for v in results.values())
         - min(v[0]["total"] for v in results.values())))
    A("")
    A("`Not Clear` is the other weak class (F1 %.4f). And `N/A` scores only %.4f "
      "even though it is *deterministically implied* by `evidence_status` -- a "
      "direct symptom of predicting the four fields independently."
      % (rep["Not Clear"]["f1-score"], rep["N/A"]["f1-score"]))
    A("")

    # ---- constraint repair: cheap lower bound on constrained decoding ----
    A("## 3b. Post-hoc constraint repair")
    A("")
    A("A deterministic projection onto the feasible label set, applied to the "
      "existing predictions. This needs no retraining and no probabilities, so it "
      "is a *lower bound* on what proper constrained joint decoding would buy.")
    A("")
    A("Rules: `promise=No` forces the other three to `N/A`; `evidence!=Yes` forces "
      "`quality=N/A`; `promise=Yes` with `timeline=N/A` takes the majority class "
      "`already`; `evidence=Yes` with `quality=N/A` takes the majority class "
      "`Clear`.")
    A("")
    A("| submission | total before | total after | delta | SCR before | SCR after |")
    A("|---|---:|---:|---:|---:|---:|")
    for fn, (s0, g0, p0) in results.items():
        rep_rows = [dict(r) for r in p0]
        for r in rep_rows:
            if norm(r["promise_status"]) == "No":
                r["verification_timeline"] = "N/A"
                r["evidence_status"] = "N/A"
                r["evidence_quality"] = "N/A"
            else:
                if norm(r["verification_timeline"]) == "N/A":
                    r["verification_timeline"] = "already"
                if norm(r["evidence_status"]) == "N/A":
                    r["evidence_status"] = "Yes"
            if norm(r["evidence_status"]) != "Yes":
                r["evidence_quality"] = "N/A"
            elif norm(r["evidence_quality"]) == "N/A":
                r["evidence_quality"] = "Clear"
        s1 = score(g0, rep_rows)
        nb0, _ = scr(p0)
        nb1, _ = scr(rep_rows)
        A("| `%s` | %.4f | %.4f | %+.4f | %.1f%% | %.1f%% |"
          % (fn, s0["total"], s1["total"], s1["total"] - s0["total"],
             100.0 * (len(p0) - nb0) / len(p0),
             100.0 * (len(rep_rows) - nb1) / len(rep_rows)))
    A("")

    A("## 4. Official reference baselines (Day et al., VeriPromiseESG4K paper, Table IV)")
    A("")
    A("| Method | PS | ES | EQ | VT | official total* |")
    A("|---|---:|---:|---:|---:|---:|")
    for name, ps, es, eq, vt in [("LLM w/o RAG", .7298, .5969, .3549, .3090),
                                 ("LLM w/ RAG", .7152, .5958, .3599, .4227)]:
        tot = .20 * ps + .30 * es + .35 * eq + .15 * vt
        A("| %s | %.4f | %.4f | %.4f | %.4f | %.4f |" % (name, ps, es, eq, vt, tot))
    A("| **ours (`%s`)** | %.4f | %.4f | %.4f | %.4f | **%.4f** |"
      % (best, s["promise_status"], s["evidence_status"],
         s["evidence_quality"], s["verification_timeline"], s["total"]))
    A("")
    A("*The paper reports overall Macro/Micro/Weighted F1 rather than the "
      "competition's weighted total; the total here is recomputed from their "
      "per-task Macro-F1 using the official weights, so it is comparable.")
    A("")

    dest = os.path.join(OUT, "official_test_scoring.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", dest)
    print()
    print("\n".join(L))


if __name__ == "__main__":
    main()
