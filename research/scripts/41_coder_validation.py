"""How much does the automatic coding of model reasons get wrong?

Script 35 assigns each model's stated reason to criterion categories with
regular expressions, and 25.8% of reasons match nothing. A reader is entitled to
ask whether the categories that do fire are the right ones, because the whole
mechanism argument rests on them.

This measures it. Sixty reasons were drawn at random from the 1,387 that script
35 collected, across all four models, and coded by hand against the same seven
categories. Agreement with the automatic coder is reported per category as
Cohen's kappa, together with the errors in each direction.

One limitation has to be stated up front and is not fixable from here: **the
manual codes and the regular expressions were produced by the same author**.
That shared authorship bounds what this measures. It is a check that the coder
does what its author intended, not an independent judgement that the intention
was right. An outside annotator would be worth having before publication; the
sample and the manual codes are stored alongside this script so one can be
obtained without redoing the work.

CPU only.
"""
import importlib.util
import io
import json
import os
import sys

import numpy as np
from sklearn.metrics import cohen_kappa_score

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
S35 = os.path.join(ROOT, "research", "artifacts", "s35")
OUT = os.path.join(ROOT, "research", "output")
os.makedirs(OUT, exist_ok=True)

_keep_ours = sys.stdout
_spec = importlib.util.spec_from_file_location(
    "s35", os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "35_explanation_probe.py"))
s35 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(s35)
_keep_theirs = sys.stdout

SHORT = {
    "V": "stated: vague wording",
    "L": "stated: link to the promise",
    "F": "unstated: no concrete figures",
    "T": "no timeline",
    "D": "insufficient detail",
    "A": "no third-party assurance",
    "P": "cites concrete figures present",
}

# Manual codes for the 60 sampled reasons, in the order sample_reasons produced
# them. Coded from the reason text alone, before comparing with the automatic
# output.
MANUAL = {
    1: "FT", 2: "P", 3: "P", 4: "P", 5: "VFD", 6: "VF", 7: "VFD", 8: "VFT",
    9: "P", 10: "VF", 11: "P", 12: "VFD", 13: "", 14: "P", 15: "P", 16: "VFD",
    17: "P", 18: "P", 19: "P", 20: "P", 21: "P", 22: "P", 23: "VFD", 24: "P",
    25: "P", 26: "P", 27: "VF", 28: "P", 29: "VFD", 30: "VF", 31: "P",
    32: "VFA", 33: "FAD", 34: "F", 35: "DA", 36: "P", 37: "FP", 38: "P",
    39: "P", 40: "", 41: "P", 42: "P", 43: "", 44: "VFD", 45: "VFD", 46: "VF",
    47: "VFD", 48: "P", 49: "VFTD", 50: "P", 51: "P", 52: "", 53: "VFD",
    54: "P", 55: "VFD", 56: "VFD", 57: "", 58: "VFD", 59: "P", 60: "P",
}


def main():
    samp = json.load(open(os.path.join(S35, "coder_sample.json"), encoding="utf-8"))
    assert len(samp) == len(MANUAL), "sample and manual codes disagree in size"

    cats = list(SHORT.values())
    auto = [s35.code(r) for _, _, r in samp]
    manual = [{SHORT[c] for c in MANUAL[i + 1]} for i in range(len(samp))]

    L = []
    A = L.append
    A("# Does the automatic coder do what it claims?")
    A("")
    A("Generated by `research/scripts/41_coder_validation.py`. %d reasons drawn "
      "at random from those script 35 collected, across all four models, coded "
      "by hand against the same seven categories." % len(samp))
    A("")
    A("**The manual codes and the regular expressions have the same author.** "
      "This therefore bounds coder error against its author's intention; it is "
      "not an independent validation, and an outside annotator would be worth "
      "having before publication. The sample and the manual codes are stored "
      "with the script so that can be done without repeating the work.")
    A("")

    A("## Per category")
    A("")
    A("| category | manual | automatic | both | Cohen kappa | missed by coder | added by coder |")
    A("|---|---:|---:|---:|---:|---:|---:|")
    kappas = []
    for c in cats:
        m = np.array([c in x for x in manual], int)
        a = np.array([c in x for x in auto], int)
        both = int((m & a).sum())
        k = (cohen_kappa_score(m, a) if len(set(m.tolist() + a.tolist())) > 1
             else float("nan"))
        if not np.isnan(k):
            kappas.append(k)
        A("| %s | %d | %d | %d | %s | %d | %d |"
          % (c, int(m.sum()), int(a.sum()), both,
             "--" if np.isnan(k) else "%.3f" % k,
             int(((m == 1) & (a == 0)).sum()), int(((m == 0) & (a == 1)).sum())))
    A("")
    A("Mean kappa over the categories where both codings used the label: "
      "**%.3f**." % (np.mean(kappas) if kappas else float("nan")))
    A("")

    A("## Whole-reason agreement")
    A("")
    exact = np.mean([a == m for a, m in zip(auto, manual)])
    jac = np.mean([len(a & m) / max(1, len(a | m)) for a, m in zip(auto, manual)])
    m_empty = sum(1 for m in manual if not m)
    a_empty = sum(1 for a in auto if not a)
    A("| measure | value |")
    A("|---|---:|")
    A("| exact set match | %.3f |" % exact)
    A("| mean Jaccard over categories | %.3f |" % jac)
    A("| reasons the coder left uncoded | %d of %d |" % (a_empty, len(auto)))
    A("| reasons the manual coding left uncoded | %d of %d |" % (m_empty, len(manual)))
    A("")

    A("## Where they disagree")
    A("")
    shown = 0
    for i, (a, m) in enumerate(zip(auto, manual)):
        if a == m or shown >= 8:
            continue
        shown += 1
        A("- **%02d** auto `%s` / manual `%s` -- %s"
          % (i + 1, ", ".join(sorted(a)) or "none",
             ", ".join(sorted(m)) or "none", samp[i][2][:120]))
    A("")

    A("## Reading")
    A("")
    A("**The two categories the argument rests on hold; the rest do not.** "
      "`stated: vague wording` and `unstated: no concrete figures` are the only "
      "two used to make a claim, and they reach kappa 0.963 and 0.861 with one "
      "and three misses respectively. Every measurement in script 35 that this "
      "project relies on -- the 0.714 citation rate on disputed rows, the 84% "
      "co-occurrence -- is built from those two.")
    A("")
    A("The auxiliary categories are weak and should be read as indicative only. "
      "`insufficient detail` misses 11 of 16, because reasons phrase it as "
      "missing 專案內容 or 投入資源 rather than the nouns the pattern lists. "
      "`no third-party assurance` fires three false positives on reasons using "
      "查證 in its ordinary sense of *verifiable* rather than *third-party "
      "assured*. `cites concrete figures present` misses nine reasons that "
      "quote figures without using a word like 數據.")
    A("")
    A("The coder is deliberately left unchanged. Tuning it against the same "
      "sixty items used to measure it would report an agreement that no longer "
      "means anything, and the two load-bearing categories need no tuning. The "
      "correct fix for the weak categories is a larger hand-coded set from an "
      "annotator who did not write the patterns.")
    A("")
    dest = os.path.join(OUT, "coder_validation.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", dest, flush=True)
    print("\n".join(L))


if __name__ == "__main__":
    main()
