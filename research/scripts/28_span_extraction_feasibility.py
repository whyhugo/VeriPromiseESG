"""Is "find the promise sentence" a task worth building?

The competition used four classification fields and ignored the two span fields
entirely, as did every participating system. But `promise_string` and
`evidence_string` are present in all three splits at 100% coverage on their
applicable rows -- 814 train, 813 val, 1,625 test for the promise -- and nobody
has touched them.

That makes span extraction the one genuinely unused resource in this dataset,
and it answers a question classification cannot: not "does this paragraph
contain a promise" but "*which sentence* is the promise". A classifier leaves an
auditor still reading the whole paragraph.

Before building anything this asks whether the task is well-posed:

  1. structure -- how long are the spans, where do they sit, how often are they
     several disjoint pieces
  2. sentence alignment -- do span boundaries land on sentence boundaries? If
     they do, the task collapses from free-form character offsets to sentence
     selection, which is far more tractable and evaluates cleanly
  3. baselines -- what do trivial strategies score, so any later model has
     something honest to beat
  4. ceiling -- if sentence selection were perfect, what would the character
     overlap be? That bounds what the reduction in (2) can deliver

Metrics are the standard extractive ones: exact match, character-level F1, and
intersection over union. CPU only.
"""
import csv
import io
import os
import re
import statistics as st
import sys
from collections import Counter

import numpy as np

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "data", "veripromiseesgdataset")
OUT = os.path.join(ROOT, "research", "output")
os.makedirs(OUT, exist_ok=True)
SEP = "｜"
SENT_END = "。！？；!?;\n"
CLAUSE_END = SENT_END + "，、,"   # clause: sentence terminators plus comma and enumeration mark

# wording that tends to introduce a forward-looking commitment
PROMISE_CUES = ["將", "預計", "規劃", "目標", "承諾", "預期", "擬", "持續推動",
                "力求", "期望", "朝", "邁向", "致力", "未來"]


def load(fn):
    return list(csv.DictReader(open(os.path.join(D, fn), encoding="utf-8-sig")))


def ok(v):
    return (v or "").strip() not in ("", "N/A")


def pieces_of(raw):
    out = []
    for p in (raw or "").split(SEP):
        p = re.sub(r"\s*\d+\s*$", "", p.strip()).strip()
        if p:
            out.append(p)
    return out


def char_mask(para, spans):
    """Boolean mask over the paragraph marking characters inside any span."""
    m = np.zeros(len(para), dtype=bool)
    for s in spans:
        start = 0
        while True:
            i = para.find(s, start)
            if i < 0:
                break
            m[i:i + len(s)] = True
            start = i + 1
            break          # first occurrence only
    return m


def split_units(para, ends=SENT_END):
    """Return (text, start, end) for each unit, keeping the terminator."""
    out, buf, start = [], [], 0
    for i, ch in enumerate(para):
        buf.append(ch)
        if ch in ends:
            t = "".join(buf)
            if t.strip():
                out.append((t, start, i + 1))
            buf, start = [], i + 1
    if buf and "".join(buf).strip():
        out.append(("".join(buf), start, len(para)))
    return out


def prf(pred, gold):
    """Character-level precision, recall, F1 between two boolean masks."""
    tp = int((pred & gold).sum())
    if tp == 0:
        return 0.0, 0.0, 0.0, 0.0
    p = tp / max(1, int(pred.sum()))
    r = tp / max(1, int(gold.sum()))
    f = 2 * p * r / (p + r)
    iou = tp / max(1, int((pred | gold).sum()))
    return p, r, f, iou


def main():
    splits = [("train", "vpesg4k_train_1000"), ("val", "vpesg4k_val_1000"),
              ("test", "vpesg4k_test_2000.csv")]
    L = []
    A = L.append
    A("# Is span extraction a task worth building?")
    A("")
    A("Generated by `research/scripts/28_span_extraction_feasibility.py`. "
      "Feasibility only -- no model is trained here.")
    A("")

    # ---------------- 1. structure ----------------
    A("## 1. Structure of the annotated spans")
    A("")
    A("| split | rows with a promise span | pieces = 1 | pieces >= 2 | median chars | median share of paragraph |")
    A("|---|---:|---:|---:|---:|---:|")
    for nm, fn in splits:
        rs = [r for r in load(fn) if ok(r.get("promise_string"))]
        np_ = [len(pieces_of(r["promise_string"])) for r in rs]
        ln = [sum(len(p) for p in pieces_of(r["promise_string"])) for r in rs]
        sh = [100.0 * sum(len(p) for p in pieces_of(r["promise_string"]))
              / max(1, len(r["data"] or "")) for r in rs]
        A("| %s | %d | %d (%.0f%%) | %d (%.0f%%) | %d | %.0f%% |"
          % (nm, len(rs), sum(1 for v in np_ if v == 1),
             100 * sum(1 for v in np_ if v == 1) / len(rs),
             sum(1 for v in np_ if v > 1),
             100 * sum(1 for v in np_ if v > 1) / len(rs),
             st.median(ln), st.median(sh)))
    A("")

    trv = [r for r in load("vpesg4k_train_1000") + load("vpesg4k_val_1000")
           if ok(r.get("promise_string"))]
    pos = []
    for r in trv:
        para, ps = r["data"] or "", pieces_of(r["promise_string"])
        idx = [para.find(p) for p in ps if para.find(p) >= 0]
        if idx:
            pos.append(100.0 * min(idx) / max(1, len(para)))
    A("The first piece starts at a median of **%.0f%%** through the paragraph "
      "(quartiles %.0f%% / %.0f%%), so the promise is not simply the opening "
      "sentence." % (st.median(pos), np.percentile(pos, 25), np.percentile(pos, 75)))
    A("")

    # ---------------- 2. sentence alignment ----------------
    A("## 2. Do spans align to sentence boundaries?")
    A("")
    A("If they do, the task reduces from free-form character offsets to picking "
      "sentences, which is easier to model and to score.")
    A("")
    exact_sent, near_sent, tot = 0, 0, 0
    ceil_f1 = []
    for r in trv:
        para = r["data"] or ""
        ps = [p for p in pieces_of(r["promise_string"]) if p in para]
        if not ps:
            continue
        tot += 1
        sents = split_units(para)
        gold = char_mask(para, ps)
        # every piece is exactly one whole sentence
        if all(any(p.strip() == s.strip() for s, _, _ in sents) for p in ps):
            exact_sent += 1
        # best achievable by choosing whole sentences
        best = np.zeros(len(para), dtype=bool)
        for s, a, b in sents:
            seg = np.zeros(len(para), dtype=bool)
            seg[a:b] = True
            if (seg & gold).sum() > 0.5 * seg.sum():
                best |= seg
        _, _, f, _ = prf(best, gold)
        ceil_f1.append(f)
        if f >= 0.95:
            near_sent += 1
    A("| | count | share |")
    A("|---|---:|---:|")
    A("| every piece is exactly one whole sentence | %d | %.0f%% |"
      % (exact_sent, 100 * exact_sent / tot))
    A("| sentence selection can reach char-F1 >= 0.95 | %d | %.0f%% |"
      % (near_sent, 100 * near_sent / tot))
    A("")
    A("**Ceiling of the sentence-selection reduction: char-F1 %.4f.** A model that "
      "only ever chose whole sentences could not do better, so sentences are the "
      "wrong unit." % float(np.mean(ceil_f1)))
    A("")

    # ---- why: the annotation is sub-sentence ----
    inside = cross = npiece = 0
    ratios, slen, plen = [], [], []
    for r in trv:
        para = r["data"] or ""
        us = split_units(para)
        slen += [len(u) for u, _, _ in us]
        for p in pieces_of(r["promise_string"]):
            i = para.find(p)
            if i < 0:
                continue
            npiece += 1
            plen.append(len(p))
            host = [(a, b) for _, a, b in us if a <= i and i + len(p) <= b]
            if host:
                inside += 1
                ratios.append(len(p) / max(1, host[0][1] - host[0][0]))
            else:
                cross += 1
    A("### Why: the annotation is sub-sentence")
    A("")
    A("| | value |")
    A("|---|---:|")
    A("| median sentence length | %d chars |" % st.median(slen))
    A("| median promise piece length | %d chars |" % st.median(plen))
    A("| pieces falling entirely inside one sentence | %d / %d (%.0f%%) |"
      % (inside, npiece, 100 * inside / npiece))
    A("| ...and the share of that sentence they occupy | median %.2f |"
      % st.median(ratios))
    A("")
    A("Annotators marked a **clause**, not a sentence. Choosing whole sentences "
      "therefore over-selects by roughly two and a half times, which is exactly "
      "what caps the ceiling at %.2f." % float(np.mean(ceil_f1)))
    A("")

    # ---- the right unit ----
    A("### The right unit is the clause")
    A("")
    A("Repeating the alignment test with the comma and enumeration mark added to "
      "the delimiters:")
    A("")
    A("| unit | median length | span boundaries landing on a unit boundary | selection ceiling (char-F1) |")
    A("|---|---:|---:|---:|")
    for nm, ends in [("sentence (。！？；)", SENT_END),
                     ("**clause** (＋，、)", CLAUSE_END)]:
        align = tot_p = 0
        ceil, ulen = [], []
        for r in trv:
            para = r["data"] or ""
            us = split_units(para, ends)
            ulen += [len(u) for u, _, _ in us]
            ps = [p for p in pieces_of(r["promise_string"]) if p in para]
            if not ps:
                continue
            g = char_mask(para, ps)
            bounds = set()
            for _, a, b in us:
                bounds.add(a)
                bounds.add(b)
            for p in ps:
                i = para.find(p)
                tot_p += 1
                if i in bounds and (i + len(p)) in bounds:
                    align += 1
            best = np.zeros(len(para), dtype=bool)
            for _, a, b in us:
                seg = np.zeros(len(para), dtype=bool)
                seg[a:b] = True
                if (seg & g).sum() > 0.5 * seg.sum():
                    best |= seg
            _, _, f, _ = prf(best, g)
            ceil.append(f)
        A("| %s | %d chars | %.0f%% | **%.4f** |"
          % (nm, st.median(ulen), 100 * align / tot_p, float(np.mean(ceil))))
    A("")
    A("**At clause level the ceiling is 0.9748 and 71% of annotated boundaries "
      "fall exactly on a clause boundary.** That turns free-form character "
      "extraction into binary labelling over clauses -- is this clause part of "
      "the promise or not -- which is a standard, well-posed sequence-labelling "
      "problem with almost no headroom lost to the reduction.")
    A("")

    # ---------------- 3. baselines ----------------
    A("## 3. Trivial baselines")
    A("")
    A("Scored on train+val with character-level metrics against the cleaned gold "
      "spans, %d rows." % tot)
    A("")

    def eval_strategy(fn_pick):
        P, R, F, I, EM = [], [], [], [], 0
        for r in trv:
            para = r["data"] or ""
            ps = [p for p in pieces_of(r["promise_string"]) if p in para]
            if not ps:
                continue
            gold = char_mask(para, ps)
            pred = fn_pick(para, split_units(para))
            p, rc, f, i = prf(pred, gold)
            P.append(p); R.append(rc); F.append(f); I.append(i)
            EM += int(np.array_equal(pred, gold))
        return (float(np.mean(P)), float(np.mean(R)), float(np.mean(F)),
                float(np.mean(I)), 100.0 * EM / len(F))

    def whole(para, sents):
        return np.ones(len(para), dtype=bool)

    def first_sent(para, sents):
        m = np.zeros(len(para), dtype=bool)
        if sents:
            m[sents[0][1]:sents[0][2]] = True
        return m

    def longest_sent(para, sents):
        m = np.zeros(len(para), dtype=bool)
        if sents:
            s = max(sents, key=lambda x: len(x[0]))
            m[s[1]:s[2]] = True
        return m

    def cue_sents(para, sents):
        m = np.zeros(len(para), dtype=bool)
        hit = [s for s in sents if any(c in s[0] for c in PROMISE_CUES)]
        for s, a, b in (hit or sents[:1]):
            m[a:b] = True
        return m

    def best_cue_sent(para, sents):
        m = np.zeros(len(para), dtype=bool)
        if not sents:
            return m
        s = max(sents, key=lambda x: sum(c in x[0] for c in PROMISE_CUES))
        m[s[1]:s[2]] = True
        return m

    A("| strategy | precision | recall | char-F1 | IoU | exact match |")
    A("|---|---:|---:|---:|---:|---:|")
    for nm, fn_ in [("whole paragraph", whole),
                    ("first sentence", first_sent),
                    ("longest sentence", longest_sent),
                    ("every sentence containing a promise cue", cue_sents),
                    ("the single sentence with most cues", best_cue_sent)]:
        p, r, f, i, em = eval_strategy(fn_)
        A("| %s | %.4f | %.4f | **%.4f** | %.4f | %.1f%% |" % (nm, p, r, f, i, em))
    A("")

    # ---------------- 4. how much is left ----------------
    A("## 4. Reading")
    A("")
    A("The promise occupies about a quarter of its paragraph and starts a median "
      "of %.0f%% of the way in, so neither \"return everything\" nor \"return the "
      "first sentence\" is close to right, which is what makes the task "
      "non-trivial." % st.median(pos))
    A("")
    A("**Sentences are the wrong unit and clauses are the right one.** Sentence "
      "selection caps at char-F1 %.4f because annotators marked clauses, not "
      "sentences; at clause level the ceiling is 0.9748 with 71%% of boundaries "
      "landing exactly. So the task should be posed as binary labelling over "
      "comma-delimited clauses, not as extractive question answering over "
      "characters." % float(np.mean(ceil_f1)))
    A("")
    A("A fifth to a quarter of the spans are several disjoint pieces, so this is "
      "discontinuous extraction rather than the single-span setting most "
      "extractive QA models assume. The clause-labelling framing handles that "
      "for free -- disjoint pieces are simply non-adjacent positive clauses -- "
      "whereas a start/end pointer model cannot represent them at all.")
    A("")
    A("The best trivial baseline reaches char-F1 %.4f. That is what a trained "
      "clause labeller has to beat, against a ceiling of 0.9748."
      % max(eval_strategy(f)[2] for f in (whole, first_sent, longest_sent,
                                          cue_sents, best_cue_sent)))
    A("")

    dest = os.path.join(OUT, "span_extraction_feasibility.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", dest, flush=True)
    print("\n".join(L))


if __name__ == "__main__":
    main()
