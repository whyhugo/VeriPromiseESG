"""Are the failed API calls ignorable, or do they carry information?

One model returned HTTP 503 on 80 of the 1,335 evidence rows, and this project
excludes those rows from its evaluation. Excluding is only safe if whatever made
a row missing is unrelated to what is being measured. An HTTP 503 is a
server-side event and *should* be independent of the paragraph, but "should be"
is an assumption, and it is the kind of assumption a reviewer is entitled to see
tested rather than asserted.

This tests it four ways:

  * **composition** -- do the excluded rows differ on the gold label, on
    paragraph and evidence length, or on the surface concreteness cues that the
    rest of this project's analysis turns on?
  * **clustering** -- are the failures a contiguous batch? If they were, they
    would be a few companies or a few minutes of wall clock, and a company is a
    writing style, which would make the missingness content-correlated.
  * **the other models** -- did the three models that *did* answer those rows
    say anything unusual about them?
  * **the right test** -- concreteness cues are heavy-tailed counts, so a
    z-test on means is the wrong instrument and will manufacture significance.
    Anything that looks significant is re-tested by permutation, on the median
    as well as the mean, and read against the number of comparisons made.

CPU only; reads the cached verdicts from script 26.
"""
import csv
import importlib.util
import io
import itertools
import json
import os
import re
import sys
from collections import Counter

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "data", "veripromiseesgdataset")
S26 = os.path.join(ROOT, "research", "artifacts", "s26")
OUT = os.path.join(ROOT, "research", "output", "missingness_check.md")
EQ = ["Clear", "Not Clear", "Misleading"]
SEED = 20260831
N_PERM = 20000

_keep = sys.stdout
_sp = importlib.util.spec_from_file_location(
    "s34", os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "34_guideline_criteria_test.py"))
s34 = importlib.util.module_from_spec(_sp)
_sp.loader.exec_module(s34)
_keep2 = sys.stdout


def na(v):
    v = (v or "").strip()
    return "N/A" if v in ("", "N/A") else v


def wilson_or_se(vals):
    v = np.asarray(vals, float)
    return float(v.mean()), float(v.std(ddof=1) / np.sqrt(len(v)))


def perm_p(a, b, stat, rng, n=N_PERM):
    """Two-sided permutation p for `stat(a) - stat(b)`."""
    obs = stat(a) - stat(b)
    pool = np.concatenate([a, b])
    na_ = len(a)
    hits = 0
    for _ in range(n):
        rng.shuffle(pool)
        if abs(stat(pool[:na_]) - stat(pool[na_:])) >= abs(obs):
            hits += 1
    return obs, hits / n


def main():
    te = [r for r in csv.DictReader(
        open(os.path.join(D, "vpesg4k_test_2000.csv"), encoding="utf-8-sig"))
        if na(r["evidence_status"]) == "Yes" and na(r["evidence_quality"]) in EQ]

    verdict = {}
    for f in sorted(os.listdir(S26)):
        if f.endswith(".json"):
            g = json.load(open(os.path.join(S26, f), encoding="utf-8"))
            verdict[f.split("__")[0]] = {k: (v[0] or "") for k, v in g.items()}
    models = sorted(verdict)

    who = [m for m in models
           if sum(1 for r in te if not verdict[m].get(r["id"], "")) > 0]
    if not who:
        _keep.write("no model has a failed call; nothing to check\n")
        return
    M = who[0]
    failed = [r for r in te if not verdict[M].get(r["id"], "")]
    answered = [r for r in te if verdict[M].get(r["id"], "")]

    L = []
    A = L.append
    A("# Are the excluded rows ignorable?")
    A("")
    A("Generated by `research/scripts/53_missingness_check.py`. `%s` returned an "
      "empty response on **%d of %d** eligible rows and this project excludes "
      "them. Everything below asks whether that exclusion can bias anything."
      % (M, len(failed), len(te)))
    A("")

    A("## 1. Composition")
    A("")
    A("| quantity | excluded rows | rows scored | z |")
    A("|---|---|---|---:|")
    tests = []

    def line(name, fn, fmt="%.3f"):
        a, sa = wilson_or_se([fn(r) for r in failed])
        b, sb = wilson_or_se([fn(r) for r in answered])
        z = (a - b) / np.sqrt(sa * sa + sb * sb)
        tests.append((name, z, fn))
        A(("| %s | " + fmt + " ± " + fmt + " | " + fmt + " ± " + fmt
           + " | %+.2f |") % (name, a, 1.96 * sa, b, 1.96 * sb, z))

    for c in EQ:
        line("gold label is `%s`" % c, lambda r, c=c: na(r["evidence_quality"]) == c)
    line("paragraph length (characters)", lambda r: len(r.get("data") or ""), "%.0f")
    line("evidence length (characters)",
         lambda r: len((r.get("evidence_string") or "").strip()), "%.0f")
    names = [n for n, _ in s34.feats_C(failed[0])]
    for j, n in enumerate(names):
        line("cue: %s" % n, lambda r, j=j: s34.feats_C(r)[j][1],
             "%.2f" if j == len(names) - 1 else "%.3f")
    A("")
    A("%d comparisons were made, so a two-sided p of 0.05 on any single one "
      "corresponds to about %.2f after a Bonferroni correction."
      % (len(tests), min(1.0, 0.05 * len(tests))))
    A("")

    A("## 2. Anything that looks significant, tested properly")
    A("")
    A("The concreteness cues are heavy-tailed counts. A z-test on their means "
      "assumes a normal sampling distribution that a variable with a long right "
      "tail does not have, so it over-rejects. Every comparison above with "
      "|z| > 1.96 is re-tested here by permutation, on the median as well as "
      "the mean.")
    A("")
    rng = np.random.default_rng(SEED)
    flagged = [t for t in tests if abs(t[1]) > 1.96]
    if not flagged:
        A("_No comparison reached |z| > 1.96._")
    else:
        A("| quantity | median: excluded / scored | diff | perm. p | "
          "mean diff | perm. p | Bonferroni |")
        A("|---|---|---:|---:|---:|---:|---:|")
        for name, z, fn in flagged:
            a = np.array([fn(r) for r in failed], float)
            b = np.array([fn(r) for r in answered], float)
            dm, pm = perm_p(a.copy(), b.copy(), np.median, rng)
            da, pa = perm_p(a.copy(), b.copy(), np.mean, rng)
            A("| %s | %.2f / %.2f | %+.3f | **%.4f** | %+.3f | %.4f | %.3f |"
              % (name, np.median(a), np.median(b), dm, pm, da, pa,
                 min(1.0, pa * len(tests))))
    A("")

    A("## 3. Are the failures a batch?")
    A("")
    ac = Counter(r["company"] for r in te)
    fc = Counter(r["company"] for r in failed)
    ids = sorted(int(r["id"]) for r in failed)
    gaps = np.diff(ids)
    runs = max((len(list(x[1])) for x in itertools.groupby(gaps)), default=0)
    A("The %d failures are spread over **%d of the %d companies** in the "
      "evaluation set, and over the id range %d--%d with a longest run of "
      "consecutive ids of %d. Per-company failure rates run %.1f%%--%.1f%%, and "
      "the highest rates sit on the smallest denominators."
      % (len(failed), len(fc), len(ac), ids[0], ids[-1], runs + 1,
         100 * min(fc[c] / ac[c] for c in fc),
         100 * max(fc[c] / ac[c] for c in fc)))
    A("")
    A("A contiguous batch would have meant a few companies or a few minutes of "
      "wall clock dropping out together, and a company is a writing style. "
      "That is not the shape of these failures.")
    A("")

    A("## 4. What the models that did answer said about those rows")
    A("")
    A("| model | said `Clear`: excluded / scored | said `Not Clear`: excluded / scored |")
    A("|---|---|---|")
    for m in models:
        if m == M:
            continue
        cells = []
        for c in ["Clear", "Not Clear"]:
            a = np.mean([verdict[m].get(r["id"], "") == c for r in failed])
            b = np.mean([verdict[m].get(r["id"], "") == c for r in answered])
            cells.append("%.3f / %.3f" % (a, b))
        A("| %s | %s | %s |" % (m, cells[0], cells[1]))
    others = [m for m in models if m != M]
    A("")
    for name, grp in (("excluded", failed), ("scored", answered)):
        un = [r for r in grp
              if all(verdict[m].get(r["id"], "") for m in others)
              and len({verdict[m][r["id"]] for m in others}) == 1]
        ok = [r for r in un
              if verdict[others[0]][r["id"]] == na(r["evidence_quality"])]
        A("- **%s rows**: the other three are unanimous on %d of %d (%.3f), and "
          "match the annotators on %d of those (%.3f)."
          % (name, len(un), len(grp), len(un) / len(grp), len(ok),
             len(ok) / max(1, len(un))))
    A("")

    A("## Reading")
    A("")
    A("The excluded rows look like the rows that were scored. The gold label "
      "distribution is indistinguishable, the lengths are indistinguishable, "
      "the failures are scattered across most companies rather than batched, "
      "and the three models that did answer them behaved on them as they did "
      "elsewhere.")
    A("")
    if flagged:
        A("One cue -- digit density -- reaches |z| > 1.96 on a mean comparison "
          "and does not survive being tested correctly: the medians are close, "
          "the permutation p on the median is far from significant, and the "
          "permutation p on the mean does not survive correction for the number "
          "of comparisons made. It is the tail of a skewed variable, not a "
          "difference in the rows.")
        A("")
    A("**So the exclusion is safe, and re-running the failed calls would cost "
      "more than it buys.** The 80 rows would have to be queried now, months "
      "after the other 1,255, from a commercial endpoint whose version is not "
      "pinned. Script 43 measures how much that matters: re-querying the same "
      "model on the same rows changes 2%--12% of its labels. Filling an "
      "ignorable gap by mixing two model snapshots into one column would "
      "introduce a real inconsistency to remove a hypothetical one.")
    A("")
    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    _keep.write("wrote %s\n" % OUT)


if __name__ == "__main__":
    main()
