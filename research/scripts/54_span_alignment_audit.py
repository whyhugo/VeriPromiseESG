"""Do the gold spans actually occur in the paragraphs they annotate?

The clause tagger locates a gold span by `paragraph.find(piece)` and, if the
piece is not found, **silently skips it**. A row whose pieces all fail to locate
gets an all-zero gold mask, and nothing anywhere reports how often that happens.

That matters in two different ways, and they need separating:

  * **character F1 is depressed but not biased.** `prf` returns zero whenever
    the intersection is empty, which is what happens on an empty gold mask
    regardless of what the model predicted. Every system pays the same penalty
    on the same rows, so comparisons between systems survive; the absolute
    numbers are pulled down.
  * **exact match is inflatable.** It is `np.array_equal(pred, gold)`. An empty
    gold mask and an empty prediction are equal, so a row nobody could score
    counts as a success for any system that happens to predict nothing there.

It also matters for training, not just scoring: `clause_labels` is built from
the same mask, so an unlocatable span teaches the model that no clause in that
paragraph is part of the answer.

This script measures the exposure, diagnoses why the pieces fail, and tests
whether a greedy sequential re-alignment recovers them. It changes no result on
its own -- the corrected scores need the five-fold runs repeated, because the
training labels move too.

CPU only.
"""
import importlib.util
import io
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "research", "output", "span_alignment_audit.md")
MIN_FRAGMENT = 4

_keep = sys.stdout
_sp = importlib.util.spec_from_file_location(
    "s32", os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "32_clause_tagger.py"))
s32 = importlib.util.module_from_spec(_sp)
_sp.loader.exec_module(s32)
_keep2 = sys.stdout

SPLITS = ["vpesg4k_train_1000", "vpesg4k_val_1000", "vpesg4k_test_2000.csv"]
FIELDS = [("promise_string", "promise_status"),
          ("evidence_string", "evidence_status")]


def na(v):
    v = (v or "").strip()
    return "N/A" if v in ("", "N/A") else v


def greedy_mask(para, piece, start=0):
    """Locate a piece as a sequence of its longest locatable fragments.

    A piece fails `find` when the annotation skipped intervening paragraph text
    without using the piece separator, or when whitespace and list bullets were
    normalised differently in the two fields. Both are repaired by matching the
    longest prefix that occurs at or after the previous match and continuing,
    which also keeps the fragments in order so a phrase cannot be matched to an
    earlier part of the paragraph.
    """
    m = np.zeros(len(para), bool)
    pos, rest, got = start, piece, 0
    while rest:
        best, at = 0, -1
        for L in range(len(rest), MIN_FRAGMENT - 1, -1):
            i = para.find(rest[:L], pos)
            if i >= 0:
                best, at = L, i
                break
        if best == 0:
            rest = rest[1:]
            continue
        m[at:at + best] = True
        got += best
        pos, rest = at + best, rest[best:]
    return m, got


def main():
    L = []
    A = L.append
    A("# Do the gold spans occur in the paragraphs they annotate?")
    A("")
    A("Generated by `research/scripts/54_span_alignment_audit.py`.")
    A("")

    A("## 1. How often does a gold piece fail to locate?")
    A("")
    A("| field | split | rows | rows with an unlocated piece | rows whose gold mask is empty | pieces lost |")
    A("|---|---|---:|---:|---:|---:|")
    stash = {}
    for field, gate in FIELDS:
        for split in SPLITS:
            rows = [r for r in s32.load(split) if na(r[gate]) == "Yes"]
            part = empty = npieces = nlost = 0
            failing = []
            for r in rows:
                para = r["data"] or ""
                ps = s32.pieces_of(r.get(field))
                npieces += len(ps)
                lost = [p for p in ps if para.find(p) < 0]
                nlost += len(lost)
                if lost:
                    part += 1
                    failing.append(r)
                if (ps and len(lost) == len(ps)) or not ps:
                    empty += 1
            A("| `%s` | %s | %d | %d (%.1f%%) | **%d (%.1f%%)** | %d / %d |"
              % (field, split.replace("vpesg4k_", "").replace(".csv", ""),
                 len(rows), part, 100 * part / len(rows), empty,
                 100 * empty / len(rows), nlost, npieces))
            if split.endswith(".csv"):
                stash[field] = (rows, failing)
        A("| | | | | | |")
    A("")
    A("**The test split is an order of magnitude worse than the training split.** "
      "0.5%--0.9% of training rows fail against 7.0%--8.5% of test rows. Whatever "
      "produced the released test file normalised the paragraph text differently "
      "from the span text; the two fields were not checked against each other.")
    A("")

    A("## 2. Why they fail")
    A("")
    A("Two causes, both visible by finding the longest prefix of a failing piece "
      "that does occur and looking at the character where it stops.")
    A("")
    rows, failing = stash["promise_string"]
    shown = {"skip": 0, "format": 0}
    for r in failing:
        para = r["data"] or ""
        for p in s32.pieces_of(r.get("promise_string")):
            if para.find(p) >= 0:
                continue
            best, at = 0, -1
            for st in range(len(para)):
                k = 0
                while k < len(p) and st + k < len(para) and para[st + k] == p[k]:
                    k += 1
                if k > best:
                    best, at = k, st
            if best < MIN_FRAGMENT:
                continue
            tail_p = p[best:best + 14]
            tail_d = para[at + best:at + best + 14]
            kind = "format" if tail_p.strip()[:3] == tail_d.strip()[:3] else "skip"
            if shown[kind] >= 2:
                continue
            shown[kind] += 1
            A("- **%s** (`id %s`): the piece stops matching after %d characters."
              % ("the annotation skipped paragraph text" if kind == "skip"
                 else "whitespace or a list bullet differs", r["id"], best))
            A("  - piece continues: `%s`" % tail_p.replace("\n", " "))
            A("  - paragraph continues: `%s`" % tail_d.replace("\n", " "))
    A("")
    A("The first kind is a discontinuous annotation whose separator was not "
      "written; the second is a formatting difference between two fields of the "
      "same row. Neither is a labelling error -- the annotator marked the right "
      "text -- and both are repairable without touching the labels.")
    A("")

    A("## 3. Does a greedy sequential re-alignment recover them?")
    A("")
    A("Match the longest prefix that occurs at or after the previous match, then "
      "continue with the remainder. Fragments shorter than %d characters are not "
      "matched, and the search only moves forward, so a phrase cannot be "
      "relocated to an earlier part of the paragraph." % MIN_FRAGMENT)
    A("")
    A("| field | failing rows | fully recovered | at least half | still under half | mean characters recovered |")
    A("|---|---:|---:|---:|---:|---:|")
    for field, _ in FIELDS:
        rows, failing = stash[field]
        full = half = under = 0
        cov = []
        for r in failing:
            para = r["data"] or ""
            lost = [p for p in s32.pieces_of(r.get(field)) if para.find(p) < 0]
            tot = sum(len(p) for p in lost)
            got = sum(greedy_mask(para, p)[1] for p in lost)
            c = got / max(1, tot)
            cov.append(c)
            full += c >= 0.99
            half += 0.5 <= c < 0.99
            under += c < 0.5
        A("| `%s` | %d | **%d** | %d | %d | **%.3f** |"
          % (field, len(failing), full, half, under, float(np.mean(cov))))
    A("")

    A("## Reading")
    A("")
    A("**Character F1 comparisons survive; exact match does not.** `prf` scores "
      "an empty intersection as zero whatever the prediction was, so every "
      "system loses the same rows and the ranking between systems is unaffected "
      "-- the absolute char-F1 numbers are simply depressed by roughly the "
      "empty-mask rate. Exact match is `array_equal`, so an empty gold mask "
      "matches an empty prediction: up to 114 of 1,625 promise rows and 113 of "
      "1,335 evidence rows can be scored correct for a system that predicted "
      "nothing. Against reported exact match of 14.1% and 12.3%, that is an "
      "exposure of about half the figure, and its size is unknown until the "
      "predictions are re-scored.")
    A("")
    A("**Training is affected too.** `clause_labels` reads the same mask, so on "
      "an unlocatable row the model is taught that no clause belongs to the "
      "answer. This is why the fix is not a scoring patch: the five-fold runs "
      "have to be repeated.")
    A("")
    A("**The repair is cheap and works.** Greedy sequential re-alignment "
      "recovers 97.1% of promise characters and 95.8% of evidence characters on "
      "the failing rows, fully recovering 95 of 120 and 92 of 125 rows. What "
      "remains should be marked unalignable and excluded explicitly rather than "
      "silently scored as an empty answer.")
    A("")
    A("**What has to be re-run**: script 32 and script 42, both fields, with the "
      "re-alignment and an explicit unalignable state, then the tagger table and "
      "the ablation table rebuilt. One GPU. Until that is done, this project's "
      "char-F1 comparisons stand and its exact-match figures do not.")
    A("")
    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    _keep.write("wrote %s\n" % OUT)


if __name__ == "__main__":
    main()
