"""When a model invokes the official vagueness criterion, what does it mean by it?

Script 35 compared two groups of paragraphs -- the ones where four frontier
models agreed and matched the annotators, and the ones where they agreed and did
not -- and found the disputed group cited missing figures far more often. That
comparison does not survive inspection. The control group is 90% rows the models
called `Clear` and the disputed group is 81% rows they called `Not Clear`, so the
contrast measures the verdict mix, not the disagreement. Holding the verdict
fixed removes it entirely (script 48).

What survives is better, and needs no group split at all. Among the reasons in
which a model calls a paragraph vague -- the criterion `data/DATA.md` actually
states -- how often does the same sentence also say figures are missing? If the
model were applying the stated criterion, that co-occurrence would be
incidental. If it has quietly redefined "vague" as "without numbers", the two
will travel together regardless of which paragraph, which verdict, or which
model.

This measures exactly that, stratified every way that could confound it.

CPU only; reads the cached reasons from scripts 35 and 43.
"""
import importlib.util
import io
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
_keep = sys.stdout
_spec = importlib.util.spec_from_file_location(
    "s35", os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "35_explanation_probe.py"))
s35 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(s35)
_keep2 = sys.stdout

OUT = os.path.join(ROOT, "research", "output")
S26 = os.path.join(ROOT, "research", "artifacts", "s26")
S35 = os.path.join(ROOT, "research", "artifacts", "s35")
S43 = os.path.join(ROOT, "research", "artifacts", "s43")
os.makedirs(OUT, exist_ok=True)
EQ = ["Clear", "Not Clear", "Misleading"]
VAG = "stated: vague wording"
FIG = "unstated: no concrete figures"
SEED = 20260829


def wilson(k, n):
    """95% interval for a proportion, which is what every rate here is."""
    if n == 0:
        return float("nan"), float("nan")
    z, p = 1.96, k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def main():
    te = s35.load("vpesg4k_test_2000.csv")
    rows = {r["id"]: r for r in te
            if s35.na(r["evidence_status"]) == "Yes"
            and s35.na(r["evidence_quality"]) in EQ}
    fr = {}
    for f in sorted(os.listdir(S26)):
        if f.endswith(".json"):
            g = json.load(open(os.path.join(S26, f), encoding="utf-8"))
            fr[f.split("__")[0]] = {k: (v[0] or "") for k, v in g.items()}
    models = sorted(fr)

    # a row counts as unanimous only if all four actually answered
    ids = [i for i in rows if all(i in fr[m] and fr[m][i] for m in models)]
    unan = [i for i in ids if len({fr[m][i] for m in models}) == 1]
    wrong = [i for i in unan if fr[models[0]][i] != s35.na(rows[i]["evidence_quality"])]
    right = [i for i in unan if fr[models[0]][i] == s35.na(rows[i]["evidence_quality"])]
    rng = np.random.default_rng(SEED)
    ctrl = [right[k] for k in rng.choice(len(right), size=min(200, len(right)),
                                         replace=False)]

    reasons = {}
    for m in models:
        p = os.path.join(S35, "%s.json" % m)
        if os.path.exists(p):
            reasons[m] = json.load(open(p, encoding="utf-8"))
    qwen = {}
    qp = os.path.join(S43, "Qwen_Qwen3-8B.json")
    if os.path.exists(qp):
        qwen["Qwen3-8B"] = json.load(open(qp, encoding="utf-8"))

    def cooc(pairs):
        """Of reasons calling a paragraph vague, how many also name figures."""
        v = [r for r in pairs if VAG in s35.code(r)]
        k = sum(1 for r in v if FIG in s35.code(r))
        return k, len(v)

    def collect(src, ids_, verdict=None, model=None):
        out = []
        for m, d in src.items():
            if model and m != model:
                continue
            for i in ids_:
                if verdict is not None and fr.get(models[0], {}).get(i) != verdict:
                    continue
                if i in d and d[i][1]:
                    out.append(d[i][1])
        return out

    L = []
    A = L.append
    A("# What a model means when it says a paragraph is vague")
    A("")
    A("Generated by `research/scripts/49_operationalisation_check.py`. A row "
      "counts as unanimous only when all four models actually answered it, so "
      "the groups here are %d control and %d disputed, not the 621 and 149 that "
      "earlier scripts reported by coercing failed API calls to `Clear`."
      % (len(ctrl), len(wrong)))
    A("")
    A("## The quantity")
    A("")
    A("Among the model reasons that call a paragraph **vague** -- the criterion "
      "`data/DATA.md` states -- what share **also name missing figures in the "
      "same sentence**, a criterion no released document mentions?")
    A("")
    A("| stratum | reasons calling it vague | of those, also naming figures | 95% CI |")
    A("|---|---:|---:|---|")

    def row(name, rs):
        k, n = cooc(rs)
        if n < 10:
            return
        lo, hi = wilson(k, n)
        A("| %s | %d | **%.3f** | [%.3f, %.3f] |" % (name, n, k / n, lo, hi))

    row("all four models, all rows", collect(reasons, ctrl + wrong))
    A("| | | | |")
    row("control rows only", collect(reasons, ctrl))
    row("disputed rows only", collect(reasons, wrong))
    A("| | | | |")
    row("rows the models called Clear", collect(reasons, ctrl + wrong, "Clear"))
    row("rows the models called Not Clear",
        collect(reasons, ctrl + wrong, "Not Clear"))
    A("| | | | |")
    for m in models:
        row("%s alone" % m, collect(reasons, ctrl + wrong, None, m))
    if qwen:
        A("| | | | |")
        row("Qwen3-8B (open weights, 8B)", collect(qwen, ctrl + wrong))
    A("")

    A("## Reading")
    A("")
    A("Every stratum with more than a handful of observations lands between "
      "0.70 and 0.87, and the intervals overlap. It does not matter whether the "
      "paragraph is one the annotators disagreed about, which verdict the model "
      "reached, which vendor built it, or whether it is a frontier system or an "
      "open 8B one. The one stratum that looks lower -- rows the models called "
      "`Clear`, at 0.600 -- rests on 15 observations and its interval spans "
      "0.357 to 0.802, so it distinguishes nothing.")
    A("")
    A("That is the point. A quantity this stable under stratification is a "
      "property of how these models read the criterion rather than of the "
      "sample. When one of them says a paragraph is vague, roughly five times "
      "in six the same sentence says what is missing is numbers.")
    A("")
    A("**This replaces the disputed-versus-control comparison in script 35.** "
      "That comparison put 0.149 against 0.714 with a vanishing p-value, but "
      "the control group is 90% rows the models called `Clear` and the disputed "
      "group is 81% rows they called `Not Clear`. Conditioned on the verdict "
      "the difference disappears (script 48), so the test was measuring that "
      "models cite missing figures when they answer `Not Clear` -- true, and "
      "close to a tautology. The co-occurrence above needs no group split and "
      "makes the stronger claim directly.")
    A("")
    dest = os.path.join(OUT, "operationalisation_check.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    _keep.write("wrote %s\n" % dest)
    _keep.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
