"""When a model invokes the official vagueness criterion, what does it mean by it?

Script 35 compared two groups of paragraphs -- the ones where four frontier
models agreed and matched the annotators, and the ones where they agreed and did
not -- and found the disputed group cited missing figures far more often. That
comparison does not survive inspection. The control group is overwhelmingly rows
the models called `Clear` and the disputed group overwhelmingly rows they called
`Not Clear`, so the contrast measures the verdict mix, not the disagreement.
Holding the verdict fixed removes it entirely (script 48).

What survives is better, and needs no group split at all. Among the reasons in
which a model calls a paragraph vague -- the criterion `data/DATA.md` actually
states -- how often does the same sentence also say figures are missing? If the
model were applying the stated criterion, that co-occurrence would be
incidental. If it has quietly redefined "vague" as "without numbers", the two
will travel together regardless of which paragraph, which verdict, or which
model.

This measures exactly that, stratified every way that could confound it.

CPU only; groups come from `probe_groups.py`, reasons from scripts 35 and 43.
"""
import importlib.util
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
_keep = sys.stdout
_spec = importlib.util.spec_from_file_location(
    "probe_groups", os.path.join(HERE, "probe_groups.py"))
pg = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(pg)
_keep2 = sys.stdout

OUT = os.path.join(ROOT, "research", "output")
os.makedirs(OUT, exist_ok=True)
VAG = "stated: vague wording"
FIG = "unstated: no concrete figures"


def wilson(k, n):
    """95% interval for a proportion, which is what every rate here is."""
    if n == 0:
        return float("nan"), float("nan")
    z, p = 1.96, k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def main():
    g = pg.groups()
    s35 = g["s35"]
    models, verdict = g["models"], g["verdict"]
    ctrl, wrong = g["control"], g["disputed"]

    def cooc(pairs):
        """Of reasons calling a paragraph vague, how many also name figures."""
        v = [r for r in pairs if VAG in s35.code(r)]
        k = sum(1 for r in v if FIG in s35.code(r))
        return k, len(v)

    def collect(src, ids_, verd=None, model=None):
        out = []
        for m, d in src.items():
            if model and m != model:
                continue
            for i in ids_:
                if verd is not None and verdict[models[0]].get(i) != verd:
                    continue
                if i in d and d[i][1]:
                    out.append(d[i][1])
        return out

    L = []
    A = L.append
    A("# What a model means when it says a paragraph is vague")
    A("")
    A("Generated by `research/scripts/49_operationalisation_check.py`. "
      + pg.provenance(g))
    A("")
    A("## The quantity")
    A("")
    A("Among the model reasons that call a paragraph **vague** -- the criterion "
      "`data/DATA.md` states -- what share **also name missing figures in the "
      "same sentence**, a criterion no released document mentions?")
    A("")
    A("| stratum | reasons calling it vague | of those, also naming figures | 95% CI |")
    A("|---|---:|---:|---|")

    def row(name, rs):
        k, n = cooc(rs)
        if n < 10:
            return
        lo, hi = wilson(k, n)
        A("| %s | %d | **%.3f** | [%.3f, %.3f] |" % (name, n, k / n, lo, hi))

    reasons, qwen = g["reasons"], g["open_reasons"]
    row("all four models, all rows", collect(reasons, ctrl + wrong))
    A("| | | | |")
    row("control rows only", collect(reasons, ctrl))
    row("disputed rows only", collect(reasons, wrong))
    A("| | | | |")
    row("rows the models called Clear", collect(reasons, ctrl + wrong, "Clear"))
    row("rows the models called Not Clear",
        collect(reasons, ctrl + wrong, "Not Clear"))
    A("| | | | |")
    for m in models:
        row("%s alone" % m, collect(reasons, ctrl + wrong, None, m))
    if qwen:
        A("| | | | |")
        for m in qwen:
            row("%s (open weights, 8B)" % m, collect(qwen, ctrl + wrong))
    A("")

    A("## Reading")
    A("")
    A("Every stratum with more than a handful of observations lands between "
      "0.70 and 0.87, and the intervals overlap. It does not matter whether the "
      "paragraph is one the annotators disagreed about, which verdict the model "
      "reached, which vendor built it, or whether it is a frontier system or an "
      "open 8B one. The one stratum that looks lower -- rows the models called "
      "`Clear` -- rests on a handful of observations and its interval spans "
      "most of the unit line, so it distinguishes nothing.")
    A("")
    A("That is the point. A quantity this stable under stratification is a "
      "property of how these models read the criterion rather than of the "
      "sample. When one of them says a paragraph is vague, roughly five times "
      "in six the same sentence says what is missing is numbers.")
    A("")
    A("**This replaces the disputed-versus-control comparison in script 35.** "
      "That comparison put 0.149 against 0.714 with a vanishing p-value, but "
      "the control group is overwhelmingly rows the models called `Clear` and "
      "the disputed group overwhelmingly rows they called `Not Clear`. "
      "Conditioned on the verdict the difference disappears (script 48), so the "
      "test was measuring that models cite missing figures when they answer "
      "`Not Clear` -- true, and close to a tautology. The co-occurrence above "
      "needs no group split and makes the stronger claim directly.")
    A("")
    dest = os.path.join(OUT, "operationalisation_check.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    _keep.write("wrote %s\n" % dest)
    _keep.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
