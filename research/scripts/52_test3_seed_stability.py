"""Is test 3's positive control a property of the data or of the RNG seed?

Script 36 asks whether reformulating the task -- feeding the classifier the
annotated evidence span instead of the whole paragraph -- helps. It does not:
all five span conditions land within 0.006 of the baseline with intervals that
cross zero. A null like that only means something if the experiment can be shown
to detect an effect at all, and the only thing licensing that is condition D,
the positive control, which replaces the input with a random span of the same
length. Script 36 reports D as [-0.0389, -0.0003].

That upper bound is 0.0003 from zero, on one draw of a bootstrap whose seed is
shared sequentially across conditions. This re-runs the identical computation
across 40 seeds and counts how often the interval excludes zero. If the answer
is "usually", the control stands. If not, test 3 is a null result of
undemonstrated sensitivity and the paper has to say so.

It also counts how often each condition predicts `Misleading`, because the
metric is a three-class macro-F1 and a class that is never predicted changes
what the number means.

CPU only; reads the cached out-of-fold predictions from script 36. Takes about
half an hour -- 40 seeds x 4,000 draws x 5 conditions x 2 f1_score calls.
"""
import csv
import io
import os

import numpy as np
from sklearn.metrics import f1_score

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "data", "veripromiseesgdataset")
S36 = os.path.join(ROOT, "research", "artifacts", "s36")
OUT = os.path.join(ROOT, "research", "output", "test3_seed_stability.md")
EQ = ["Clear", "Not Clear", "Misleading"]
N_SEED = 40
N_DRAW = 4000
COND = {"B": "the annotated evidence span",
        "C": "the annotated promise + evidence",
        "D": "a random span of the same length (positive control)",
        "E": "the predicted evidence span",
        "F": "the predicted promise + evidence"}


def na(v):
    v = (v or "").strip()
    return "N/A" if v in ("", "N/A") else v


def main():
    te = [r for r in csv.DictReader(open(os.path.join(D, "vpesg4k_test_2000.csv"),
                                         encoding="utf-8-sig"))
          if na(r["evidence_status"]) == "Yes"
          and na(r["evidence_quality"]) in EQ]
    y = np.array([EQ.index(na(r["evidence_quality"])) for r in te])

    P = {}
    for c in "ABCDEF":
        f = os.path.join(S36, "cond_%s.npz" % c)
        if os.path.exists(f):
            P[c] = np.load(f)["test"].argmax(1)

    L = []
    A = L.append
    A("# Does test 3's positive control survive a change of random seed?")
    A("")
    A("Generated by `research/scripts/52_test3_seed_stability.py`. %d rows, "
      "%d seeds x %d bootstrap draws per condition, using the same "
      "`f1_score(average=\"macro\")` call as script 36."
      % (len(y), N_SEED, N_DRAW))
    A("")
    A("| condition | input | point estimate | mean 2.5th | mean 97.5th | "
      "seeds excluding 0 |")
    A("|---|---|---:|---:|---:|---:|")

    rows = {}
    for c in sorted(P):
        if c == "A":
            continue
        point = (f1_score(y, P[c], average="macro", zero_division=0)
                 - f1_score(y, P["A"], average="macro", zero_division=0))
        los, his, excl = [], [], 0
        for seed in range(N_SEED):
            rng = np.random.default_rng(1000 + seed)
            d = []
            for _ in range(N_DRAW):
                k = rng.integers(0, len(y), len(y))
                if len(set(y[k])) < 2:
                    continue
                d.append(f1_score(y[k], P[c][k], average="macro", zero_division=0)
                         - f1_score(y[k], P["A"][k], average="macro",
                                    zero_division=0))
            lo, hi = np.percentile(d, 2.5), np.percentile(d, 97.5)
            los.append(lo)
            his.append(hi)
            excl += int(lo > 0 or hi < 0)
        rows[c] = (point, float(np.mean(los)), float(np.mean(his)), excl)
        A("| %s | %s | %+.4f | %+.4f | %+.4f | **%d / %d** |"
          % (c, COND.get(c, ""), point, np.mean(los), np.mean(his), excl,
             N_SEED))
    A("")

    A("## How often is `Misleading` predicted?")
    A("")
    A("| condition | %s |" % " | ".join(sorted(P)))
    A("|---%s|" % ("|---" * len(P)))
    A("| times predicted | %s |"
      % " | ".join(str(int((P[c] == 2).sum())) for c in sorted(P)))
    A("")

    A("## Reading")
    A("")
    d = rows.get("D")
    if d:
        A("**The positive control does not hold.** Condition D -- the one that "
          "replaces the evidence with random text of the same length, and the "
          "only reason to believe this experiment can detect anything -- "
          "excludes zero on **%d of %d seeds**. Its mean interval is "
          "[%+.4f, %+.4f], which crosses zero. The published "
          "[-0.0389, -0.0003] is one draw landing on the favourable side of a "
          "boundary the seed decides." % (d[3], N_SEED, d[1], d[2]))
        A("")
    A("The other four conditions exclude zero on **no seed at all**, which is "
      "consistent with their point estimates but tells us nothing on its own: "
      "with the control failing, this design has no demonstrated sensitivity, "
      "so its nulls are uninformative rather than negative. Test 3 should be "
      "reported as a null result of undemonstrated sensitivity, not as an "
      "exclusion of the task-formalisation explanation.")
    A("")
    A("**No condition predicts `Misleading` even once.** The metric is "
      "therefore a two-class macro-F1 scaled by 2/3, and every delta above is "
      "shrunk by that same constant. This does not change any sign, but it "
      "means the numbers are not comparable with a three-class macro-F1 "
      "reported elsewhere.")
    A("")
    A("**What would fix it.** Three training seeds per condition and a paired "
      "test over the folds, rather than one fine-tuning run per condition with "
      "a bootstrap over test rows only. Script 42 establishes that seed "
      "variance on a comparable task is about +/-0.0066, which is a third of "
      "the effect D is trying to detect.")
    A("")
    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
