"""How much harder is `evidence_quality` than the other three, really?

The obvious comparison -- macro-F1 per subtask -- is not one. The four fields
have two, three, four and five classes, and `evidence_quality`'s fourth class
has three test rows. Averaging an F1 of 0.0000 over a three-row class into a
four-way mean removes a quarter of the score for a reason that has nothing to do
with the difficulty of the field.

This reports the comparison on a scale where the four are comparable: balanced
accuracy, chance-corrected as (BA - 1/K) / (1 - 1/K), so 0 is chance and 1 is
perfect regardless of how many classes a field has. It also prints per-class F1,
because the aggregate hides which class is actually failing, and macro-F1 with
and without the three-row class, so a reader can see exactly what that class is
worth.

CPU only; reads the competition submission and the gold labels.
"""
import csv
import io
import os
import sys

import numpy as np
from sklearn.metrics import balanced_accuracy_score, f1_score

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "data", "veripromiseesgdataset")
SUB = os.path.join(ROOT, "submissions")
OUT = os.path.join(ROOT, "research", "output")
os.makedirs(OUT, exist_ok=True)

SYSTEM = "ens_3way_tuned.csv"
FIELDS = ["promise_status", "evidence_status", "evidence_quality",
          "verification_timeline"]
CIRCLED = {"promise_status": "1", "evidence_status": "2",
           "evidence_quality": "3", "verification_timeline": "4"}
RARE = "Misleading"


def na(v):
    v = (v or "").strip()
    return "N/A" if v in ("", "N/A") else v


def main():
    te = list(csv.DictReader(open(os.path.join(D, "vpesg4k_test_2000.csv"),
                                  encoding="utf-8-sig")))
    pred = {r["id"]: r for r in csv.DictReader(
        open(os.path.join(SUB, SYSTEM), encoding="utf-8-sig"))}
    te = [r for r in te if r["id"] in pred]

    L = []
    A = L.append
    A("# Which subtask is hard, on a scale where the four are comparable")
    A("")
    A("Generated by `research/scripts/51_subtask_difficulty.py` from "
      "`submissions/%s` on the %d test rows." % (SYSTEM, len(te)))
    A("")
    A("| subtask | classes | macro-F1 | macro-F1 without the 3-row class | "
      "balanced acc. | chance | **chance-corrected** |")
    A("|---|---:|---:|---:|---:|---:|---:|")
    for f in FIELDS:
        y = [na(r[f]) for r in te]
        p = [na(pred[r["id"]][f]) for r in te]
        labs = sorted(set(y))
        k = len(labs)
        mf = f1_score(y, p, labels=labs, average="macro", zero_division=0)
        keep = [l for l in labs if l != RARE]
        mf2 = f1_score(y, p, labels=keep, average="macro", zero_division=0)
        ba = balanced_accuracy_score(y, p)
        cc = (ba - 1.0 / k) / (1 - 1.0 / k)
        A("| %s `%s` | %d | %.4f | %s | %.4f | %.3f | **%+.3f** |"
          % (CIRCLED[f], f, k, mf,
             "%.4f" % mf2 if RARE in labs else "--", ba, 1.0 / k, cc))
    A("")

    A("## Per class, so the aggregate is not doing the arguing")
    A("")
    A("| subtask | class | test rows | F1 |")
    A("|---|---|---:|---:|")
    for f in FIELDS:
        y = [na(r[f]) for r in te]
        p = [na(pred[r["id"]][f]) for r in te]
        labs = sorted(set(y))
        per = f1_score(y, p, labels=labs, average=None, zero_division=0)
        for l, v in zip(labs, per):
            A("| %s | `%s` | %d | %.4f |"
              % (CIRCLED[f], l, sum(1 for x in y if x == l), v))
    A("")

    A("## Reading")
    A("")
    A("**Macro-F1 overstates the gap.** `evidence_quality` scores 0.4642 "
      "against 0.6545 for `verification_timeline`, but 0.1547 of that "
      "difference is one class with three test rows scoring zero. Drop it and "
      "the two are 0.6189 and 0.6545 -- close.")
    A("")
    A("**The gap is real on a chance-corrected scale, and it is large.** "
      "Balanced accuracy corrected for the number of classes puts "
      "`evidence_quality` at +0.289 against +0.536, +0.594 and +0.612 for the "
      "other three: **less than half of any of them**, and this measure gives "
      "the three-row class no more weight than its recall deserves.")
    A("")
    A("**The failing class is `Not Clear`, F1 0.3556 on 226 rows.** Not a rare "
      "class, and not one whose definition is ambiguous in the way "
      "`Misleading`'s is. Every other field's minority class scores 0.57 to "
      "0.70. That is the quantity the rest of this project is about.")
    A("")
    dest = os.path.join(OUT, "subtask_difficulty.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", dest, flush=True)


if __name__ == "__main__":
    main()
