"""How much does an LLM vote actually add, once the weight is chosen honestly?

The first look at this swept a mixing weight and reported the best cell: +0.0186
on verification_timeline, +0.0091 on evidence_quality. Those are upper bounds,
not results. The weight was picked on the same 601 rows the gain was measured on,
and on that sample a difference of 0.008 sits inside the noise.

Here the subsample is split in half, stratified. The weight is fitted on one
half and the gain is read off the other, then the halves swap and the two
estimates are averaged, so every number reported is out-of-sample with respect
to the weight. The oracle column stays in the table as the ceiling it is.

Also fits a per-subtask model assignment: for each subtask, which of the six
candidates gives the best held-out gain. A model that wins one field and loses
three is still worth having if it is only ever consulted about that field.

CPU only, reading the cached probability matrices.
"""
import csv
import io
import json
import os
import sys

import numpy as np
from sklearn.metrics import f1_score
from sklearn.model_selection import StratifiedKFold

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "data", "veripromiseesgdataset")
OUT = os.path.join(ROOT, "research", "output")
S21 = os.path.join(ROOT, "research", "artifacts", "s21")
S18 = os.path.join(ROOT, "research", "artifacts", "s18")
SEED = 20260824

LABELS = {
    "promise_status": ["No", "Yes"],
    "evidence_status": ["N/A", "No", "Yes"],
    "evidence_quality": ["N/A", "Not Clear", "Clear", "Misleading"],
    "verification_timeline": ["N/A", "already", "within_2_years",
                              "between_2_and_5_years", "more_than_5_years"],
}
WEIGHTS = np.arange(0.0, 0.81, 0.05)


def load(fn):
    return list(csv.DictReader(open(os.path.join(D, fn), encoding="utf-8-sig")))


def na(v):
    v = (v or "").strip()
    return "N/A" if v in ("", "N/A") else v


def macro(y, p):
    return f1_score(y, p, average="macro", zero_division=0)


def main():
    trv = load("vpesg4k_train_1000") + load("vpesg4k_val_1000")
    pick = json.load(open(os.path.join(S21, "subsample.json")))["picked_rows"]
    rows = [trv[i] for i in pick]

    models = sorted(f[:-4] for f in os.listdir(S21) if f.endswith(".npz"))
    P = {m: np.load(os.path.join(S21, m + ".npz")) for m in models}
    print("models: %s" % ", ".join(models), flush=True)

    L = []
    A = L.append
    A("# What an LLM vote adds, with the weight chosen out of sample")
    A("")
    A("Generated by `research/scripts/22_llm_vote_weights.py`. The %d-row "
      "stratified subsample of train+val is split in half; the mixing weight is "
      "fitted on one half and the gain measured on the other, then swapped and "
      "averaged. Test is untouched." % len(rows))
    A("")
    A("Mixed as `(1-w) * encoder_oof + w * llm`, argmax over the result. The "
      "encoder side is out-of-fold, so it is not advantaged on these rows either.")
    A("")

    best_per_task = {}
    for f in LABELS:
        y = np.array([LABELS[f].index(na(r[f])) for r in rows])
        eo = np.load(os.path.join(S18, "%s.npz" % f.replace("_", "")))["oof"][pick]
        base = macro(y, eo.argmax(1))

        A("## `%s`  (encoder alone %.4f)" % (f, base))
        A("")
        A("| model | oracle w | oracle gain | **honest gain** | fitted w (half A / B) |")
        A("|---|---:|---:|---:|---|")
        skf = StratifiedKFold(n_splits=2, shuffle=True, random_state=SEED)
        folds = list(skf.split(np.zeros(len(y)), y))
        rank = []
        for m in models:
            lp = P[m][f]
            orc = [macro(y, ((1 - w) * eo + w * lp).argmax(1)) for w in WEIGHTS]
            oi = int(np.argmax(orc))

            honest, ws = [], []
            for tr, te in folds:
                sc = [macro(y[tr], ((1 - w) * eo[tr] + w * lp[tr]).argmax(1))
                      for w in WEIGHTS]
                w = WEIGHTS[int(np.argmax(sc))]
                ws.append(w)
                honest.append(macro(y[te], ((1 - w) * eo[te] + w * lp[te]).argmax(1))
                              - macro(y[te], eo[te].argmax(1)))
            h = float(np.mean(honest))
            rank.append((h, m, float(np.mean(ws))))
            A("| %s | %.2f | %+.4f | **%+.4f** | %.2f / %.2f |"
              % (m, WEIGHTS[oi], orc[oi] - base, h, ws[0], ws[1]))
        rank.sort(reverse=True)
        best_per_task[f] = rank[0]
        A("")

    A("## Best model per subtask, held out")
    A("")
    A("| subtask | best model | honest gain | mean fitted weight |")
    A("|---|---|---:|---:|")
    tot = 0.0
    COMP_W = {"promise_status": 0.20, "evidence_status": 0.30,
              "evidence_quality": 0.35, "verification_timeline": 0.15}
    for f, (h, m, w) in best_per_task.items():
        A("| `%s` | %s | **%+.4f** | %.2f |" % (f, m, h, w))
        tot += COMP_W[f] * max(0.0, h)
    A("")
    A("Assigning each subtask its own best model and keeping only the "
      "non-negative gains, the weighted total moves by **%+.4f**. That is still "
      "an optimistic reading -- the per-subtask winner is itself picked on these "
      "601 rows -- but the weights behind it are out of sample." % tot)
    A("")

    dest = os.path.join(OUT, "llm_vote_weights.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", dest, flush=True)
    print("\n".join(L))


if __name__ == "__main__":
    main()
