"""Pick the paragraphs the paper should print.

Every claim in this project about `evidence_quality` is a rate: how often four
models agreed, how often a reason that says "vague" also says "no figures". A
reader who has never seen one of these paragraphs cannot check any of it. This
script selects a small number of real rows to print verbatim, with the gold
label, what the four models said, and the reason one of them gave.

Selection is by fixed rules stated in the report it writes, so the choice is not
a matter of taste:

  case 1  a disputed row -- four models unanimous and wrong -- where the gold
          label is `Clear`, the models said `Not Clear`, and the reason both
          invokes the stated vagueness criterion and names missing figures. This
          is the modal disputed row and the mechanism in one paragraph.
  case 2  the same, but where the evidence carries a *qualitative* mechanism
          (a procedure, a body, a review) and no number. This is where the two
          criteria come apart most visibly.
  case 3  a reverse-direction row: gold `Not Clear`, all four models `Clear`.
          Roughly a sixth of the disputed set runs this way and the paper says
          so; printing one keeps that sentence honest.
  case 4  a control row, unanimous and correct, for contrast.

Within each case the shortest paragraph wins, so the printed text fits a page.

CPU only; reads the cached verdicts from script 26 and reasons from script 35.
"""
import importlib.util
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
_keep = sys.stdout
_spec = importlib.util.spec_from_file_location(
    "probe_groups", os.path.join(HERE, "probe_groups.py"))
pg = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(pg)
_keep2 = sys.stdout

OUT = os.path.join(ROOT, "research", "output")
VAG = "stated: vague wording"
FIG = "unstated: no concrete figures"


def main():
    g = pg.groups()
    s35 = g["s35"]
    rows, fr, models = g["rows"], g["verdict"], g["models"]
    reasons = g["reasons"]
    disputed, control = g["disputed"], g["control"]

    def with_reason(i):
        """Every reason given for this row, tagged with the coder's classes."""
        out = []
        for m in models:
            r = reasons.get(m, {}).get(i)
            if r and r[1]:
                out.append((m, r[1], set(s35.code(r[1]))))
        return out

    def txt(i):
        return (rows[i].get("evidence_string") or "").strip()

    def para(i):
        return (rows[i].get("data") or "").strip()

    # ---- case 1 and 2 -----------------------------------------------------
    c12 = []
    for i in disputed:
        if s35.na(rows[i]["evidence_quality"]) != "Clear":
            continue
        if fr[models[0]][i] != "Not Clear":
            continue
        rs = [x for x in with_reason(i) if VAG in x[2] and FIG in x[2]]
        if rs:
            c12.append((i, rs))

    QUALITATIVE = ["委員會", "小組", "查證", "稽核", "審查", "制度", "辦法",
                   "流程", "程序", "機制", "認證", "訓練", "課程"]

    def has_mechanism(i):
        t = txt(i) or para(i)
        return sum(1 for w in QUALITATIVE if w in t)

    c1 = sorted([x for x in c12 if has_mechanism(x[0]) == 0],
                key=lambda x: len(txt(x[0]) or para(x[0])))
    c2 = sorted([x for x in c12 if has_mechanism(x[0]) >= 2],
                key=lambda x: len(txt(x[0]) or para(x[0])))
    if not c1:
        c1 = sorted(c12, key=lambda x: len(txt(x[0]) or para(x[0])))

    # ---- case 3: the other direction --------------------------------------
    c3 = sorted([(i, with_reason(i)) for i in disputed
                 if s35.na(rows[i]["evidence_quality"]) == "Not Clear"
                 and fr[models[0]][i] == "Clear"],
                key=lambda x: len(txt(x[0]) or para(x[0])))

    # ---- case 4: a control row --------------------------------------------
    c4 = sorted([(i, with_reason(i)) for i in control
                 if s35.na(rows[i]["evidence_quality"]) == "Clear"
                 and any(FIG not in x[2] for x in with_reason(i))],
                key=lambda x: len(txt(x[0]) or para(x[0])))

    L = []
    A = L.append
    A("# Paragraphs the paper should print")
    A("")
    A("Generated by `research/scripts/50_example_paragraphs.py`. Selection "
      "rules are in the script docstring and are fixed in advance; within each "
      "case the shortest paragraph wins so the printed text fits a page.")
    A("")
    A(pg.provenance(g))
    A("")
    A("Candidates per case: c1 %d, c2 %d, c3 %d, c4 %d."
      % (len(c1), len(c2), len(c3), len(c4)))
    A("")

    def emit(title, pool, n=2):
        A("## %s" % title)
        A("")
        if not pool:
            A("_no row satisfies this rule_")
            A("")
            return
        for i, rs in pool[:n]:
            r = rows[i]
            A("### id `%s`" % i)
            A("")
            A("- gold `evidence_quality`: **%s**" % s35.na(r["evidence_quality"]))
            A("- four models: %s" % ", ".join(
                "%s=`%s`" % (m, fr[m][i]) for m in models))
            A("- paragraph (%d chars): %s" % (len(para(i)), para(i)))
            A("- gold `promise_string`: %s"
              % (r.get("promise_string") or "").strip())
            A("- gold `evidence_string` (%d chars): %s" % (len(txt(i)), txt(i)))
            for m, t, cls in rs:
                A("- reason, %s: %s" % (m, t))
                A("  - coder classes: %s" % (", ".join(sorted(cls)) or "none"))
            A("")

    emit("Case 1 -- gold Clear, four models Not Clear, reason says vague AND "
         "no figures, evidence carries no qualitative mechanism", c1, 3)
    emit("Case 2 -- same, but the evidence describes a mechanism (a body, a "
         "procedure, an audit) with no number in it", c2, 3)
    emit("Case 3 -- the other direction: gold Not Clear, four models Clear", c3, 2)
    emit("Case 4 -- control: unanimous and correct", c4, 2)

    dest = os.path.join(OUT, "example_paragraphs.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    _keep.write("wrote %s\n" % dest)


if __name__ == "__main__":
    main()
