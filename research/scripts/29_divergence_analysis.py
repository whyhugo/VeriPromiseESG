"""Where four frontier models agree with each other and not with the annotators.

Script 26 produced something more useful than the headline it was run for. Four
models from three providers judged the same 1,335 test paragraphs, and on the
three Misleading rows they did not merely all fail -- they gave the *same wrong
answer, row for row*. That is not four independent errors. It is a shared
reading of the text that differs from the annotators'.

Those rows are already paid for, and they are the material for a question the
classification results cannot reach: **when machines converge on a judgement the
annotators did not make, what are the annotators seeing?**

Three things are measured:

  1. how much the four models agree with each other, against how much they agree
     with the gold standard -- if inter-model agreement is far higher, they share
     a systematic reading
  2. the unanimous-and-wrong rows, broken out by gold label, which says whether
     the divergence is spread evenly or concentrated in one judgement
  3. what those rows look like -- length, digit density, the guideline's own
     specificity cues -- against the unanimous-and-right rows, so the difference
     is characterised rather than just counted

No new inference; this reads the cached predictions. CPU only.
"""
import csv
import io
import json
import os
import re
import statistics as st
import sys
from collections import Counter

import numpy as np

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "data", "veripromiseesgdataset")
OUT = os.path.join(ROOT, "research", "output")
S26 = os.path.join(ROOT, "research", "artifacts", "s26")
os.makedirs(OUT, exist_ok=True)

EQ = ["Clear", "Not Clear", "Misleading"]
CUES = [("digit", r"[0-9０-９]"),
        ("percent", r"[%％]|百分之"),
        ("year", r"(19|20)\d{2}\s*年|民國\s*\d+\s*年"),
        ("unit", r"(公?噸|kg|公斤|度|kWh|MWh|MW|GJ|tCO2e|件|人次|小時|平方公尺|公升)"),
        ("money", r"(新臺幣|新台幣|NT\$|億元|萬元|千元)"),
        ("certification", r"(ISO\s?\d+|認證|查證|第三方|外部稽核|GRI|SASB|TCFD)"),
        ("org unit", r"(委員會|工作小組|專案小組|事業處|中心|辦公室|董事會)")]


def load(fn):
    return list(csv.DictReader(open(os.path.join(D, fn), encoding="utf-8-sig")))


def na(v):
    v = (v or "").strip()
    return "N/A" if v in ("", "N/A") else v


def main():
    te = load("vpesg4k_test_2000.csv")
    rows = [r for r in te if na(r["evidence_status"]) == "Yes"
            and na(r["evidence_quality"]) in EQ]
    by_id = {r["id"]: r for r in rows}

    preds = {}
    for f in sorted(os.listdir(S26)):
        if not f.endswith(".json"):
            continue
        m = f.split("__")[0]
        got = json.load(open(os.path.join(S26, f), encoding="utf-8"))
        # an empty verdict is a failed API call, not a `Clear`
        preds[m] = {rid: (v[0] or "") for rid, v in got.items()}
    models = sorted(preds)
    ids = [r["id"] for r in rows
           if all(r["id"] in preds[m] and preds[m][r["id"]] for m in models)]
    gold = {i: na(by_id[i]["evidence_quality"]) for i in ids}

    L = []
    A = L.append
    A("# When the machines agree with each other and not with the annotators")
    A("")
    A("Generated by `research/scripts/29_divergence_analysis.py` from the cached "
      "predictions of script 26. %d test paragraphs, %d models: %s."
      % (len(ids), len(models), ", ".join(models)))
    A("")

    # ---------- 1. agreement structure ----------
    A("## 1. Models agree with each other more than with the gold standard")
    A("")
    A("| pair | agreement |")
    A("|---|---:|")
    pair_agree = []
    for a in range(len(models)):
        for b in range(a + 1, len(models)):
            ma, mb = models[a], models[b]
            v = np.mean([preds[ma][i] == preds[mb][i] for i in ids])
            pair_agree.append(v)
            A("| %s vs %s | %.3f |" % (ma, mb, v))
    A("")
    A("| model | agreement with gold |")
    A("|---|---:|")
    gold_agree = []
    for m in models:
        v = np.mean([preds[m][i] == gold[i] for i in ids])
        gold_agree.append(v)
        A("| %s | %.3f |" % (m, v))
    A("")
    A("**Mean model-to-model agreement %.3f, mean model-to-gold agreement %.3f.** "
      "The four systems are %.0f%% more consistent with one another than any of "
      "them is with the annotators, which is the signature of a shared reading "
      "rather than of independent noise."
      % (np.mean(pair_agree), np.mean(gold_agree),
         100 * (np.mean(pair_agree) / np.mean(gold_agree) - 1)))
    A("")

    # ---------- 2. unanimity ----------
    unan = [i for i in ids if len({preds[m][i] for m in models}) == 1]
    unan_right = [i for i in unan if preds[models[0]][i] == gold[i]]
    unan_wrong = [i for i in unan if preds[models[0]][i] != gold[i]]
    split = [i for i in ids if i not in unan]

    A("## 2. The unanimous rows")
    A("")
    A("| | count | share of all rows |")
    A("|---|---:|---:|")
    A("| all four agree | %d | %.0f%% |" % (len(unan), 100 * len(unan) / len(ids)))
    A("| ...and match the gold label | %d | %.0f%% |"
      % (len(unan_right), 100 * len(unan_right) / len(ids)))
    A("| ...and **all four are wrong together** | %d | %.0f%% |"
      % (len(unan_wrong), 100 * len(unan_wrong) / len(ids)))
    A("| the models split | %d | %.0f%% |" % (len(split), 100 * len(split) / len(ids)))
    A("")
    A("When they agree they are right %.0f%% of the time; the remaining %d rows "
      "are the interesting ones."
      % (100 * len(unan_right) / max(1, len(unan)), len(unan_wrong)))
    A("")

    A("### What the gold label is on the unanimous-and-wrong rows")
    A("")
    A("| gold label | rows in test | unanimous-and-wrong | share of that class | what the models said instead |")
    A("|---|---:|---:|---:|---|")
    for c in EQ:
        n_gold = sum(1 for i in ids if gold[i] == c)
        sub = [i for i in unan_wrong if gold[i] == c]
        said = Counter(preds[models[0]][i] for i in sub)
        A("| `%s` | %d | %d | %.0f%% | %s |"
          % (c, n_gold, len(sub), 100 * len(sub) / max(1, n_gold),
             ", ".join("%s x%d" % (k, v) for k, v in said.most_common()) or "--"))
    A("")

    # ---------- 3. what those rows look like ----------
    A("## 3. What separates the unanimous-and-wrong rows")
    A("")
    A("Compared against the rows where all four agree *and* are right.")
    A("")

    def profile(idlist):
        if not idlist:
            return None
        paras = [by_id[i]["data"] or "" for i in idlist]
        evs = [by_id[i].get("evidence_string") or "" for i in idlist]
        out = {"n": len(idlist),
               "para_len": st.median([len(p) for p in paras]),
               "ev_len": st.median([len(e) for e in evs]),
               "digit_density": 100 * float(np.mean(
                   [len(re.findall(r"[0-9０-９]", p)) / max(1, len(p)) for p in paras]))}
        for nm, pat in CUES:
            out[nm] = float(np.mean([bool(re.search(pat, p)) for p in paras]))
        return out

    pr = profile(unan_right)
    pw = profile(unan_wrong)
    A("| feature | unanimous & right | unanimous & wrong | difference |")
    A("|---|---:|---:|---:|")
    A("| rows | %d | %d | |" % (pr["n"], pw["n"]))
    A("| median paragraph length | %d | %d | %+d |"
      % (pr["para_len"], pw["para_len"], pw["para_len"] - pr["para_len"]))
    A("| median evidence-span length | %d | %d | %+d |"
      % (pr["ev_len"], pw["ev_len"], pw["ev_len"] - pr["ev_len"]))
    A("| digits per 100 chars | %.2f | %.2f | %+.2f |"
      % (pr["digit_density"], pw["digit_density"],
         pw["digit_density"] - pr["digit_density"]))
    for nm, _ in CUES:
        A("| contains %s | %.3f | %.3f | %+.3f |" % (nm, pr[nm], pw[nm], pw[nm] - pr[nm]))
    A("")

    # ---------- 4. the three Misleading rows ----------
    A("## 4. The three Misleading rows in full")
    A("")
    mis = [i for i in ids if gold[i] == "Misleading"]
    for i in mis:
        r = by_id[i]
        A("**id %s** — all four models said `%s`" % (i, preds[models[0]][i]))
        A("")
        A("- promise span: %s" % ((r.get("promise_string") or "")[:200].replace("\n", " ")))
        A("- evidence span: %s" % ((r.get("evidence_string") or "")[:200].replace("\n", " ")))
        A("")
    A("")

    A("## Reading")
    A("")
    A("The four systems agree with each other markedly more than any of them "
      "agrees with the gold standard, and they are unanimous on %.0f%% of rows. "
      "On %d of those they are unanimously wrong."
      % (100 * len(unan) / len(ids), len(unan_wrong)))
    A("")
    A("That set is not spread evenly across the labels, which is the finding: "
      "the divergence is a disagreement about a particular judgement rather than "
      "general noise. Read with the earlier result that nine interventions could "
      "not move `evidence_quality`, this points the same way -- the models are "
      "not failing to read the paragraphs, they are reading them consistently "
      "and applying a different standard of what counts as adequate evidence.")
    A("")
    A("This is the material for an error analysis that does not require a better "
      "model: a set of paragraphs, already labelled by people and already judged "
      "unanimously by four frontier systems, on which the two disagree.")
    A("")

    dest = os.path.join(OUT, "divergence_analysis.md")
    open(dest, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", dest, flush=True)
    print("\n".join(L))


if __name__ == "__main__":
    main()
